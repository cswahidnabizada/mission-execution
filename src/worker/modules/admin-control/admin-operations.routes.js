export function registerAdminOperationsRoutes(router){
  router.get('/api/platform/admin/operations',async({request,env})=>{try{await requirePlatformAdministrator(request,env);const url=new URL(request.url);return json({success:true,operations:await listPlatformAdminOperations(env,{limit:url.searchParams.get('limit')||50,scopeKey:url.searchParams.get('scope')||null})});}catch(e){return fail(e);}});
  router.get(/^\/api\/platform\/admin\/operations\/(?<operationId>\d+)$/,async({request,env,params})=>{try{await requirePlatformAdministrator(request,env);const operation=await getPlatformAdminOperation(env,Number(params.operationId));if(!operation)throw Object.assign(new Error('Administrative operation not found'),{status:404,code:'PLATFORM_ADMIN_OPERATION_NOT_FOUND'});return json({success:true,operation});}catch(e){return fail(e);}});
}
