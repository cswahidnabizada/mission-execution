export function registerAdminGovernanceRoutes(router){
  router.get('/api/platform/admin/privacy/summary',async({request,env})=>{try{await requirePlatformAdministrator(request,env);return json({success:true,...await getPrivacyAdministrationSummary(env)});}catch(e){return fail(e);}});
  router.get('/api/platform/admin/consent-policies',async({request,env})=>{try{await requirePlatformAdministrator(request,env);return json({success:true,policies:await listConsentPolicies(env)});}catch(e){return fail(e);}});
  router.post('/api/platform/admin/consent-policies',async({request,env,requestId})=>{try{const actor=await requirePlatformAdministrator(request,env);const b=await readJson(request);const policy=await upsertConsentPolicy(env,actor,{companyId:b.companyId,countryCode:b.countryCode,purposeCode:b.purposeCode,policyVersion:b.policyVersion,title:b.title,policyText:b.policyText,requireConsent:b.requireConsent,withdrawalEffect:b.withdrawalEffect},requestId);return json({success:true,policy},201);}catch(e){return fail(e);}});
  router.get('/api/platform/admin/analytics-governance',async({request,env})=>{try{await requirePlatformAdministrator(request,env);return json({success:true,...await getAnalyticsGovernance(env)});}catch(e){return fail(e);}});
  router.patch(/^\/api\/platform\/admin\/analytics-governance\/(?<policyId>\d+)$/,async({request,env,params,requestId})=>{try{const actor=await requirePlatformAdministrator(request,env);const b=await readJson(request);const policy=await updateAnalyticsPolicy(env,actor,Number(params.policyId),{purposeCode:b.purposeCode,classification:b.classification,retentionPolicyCode:b.retentionPolicyCode,allowedMetricCodes:b.allowedMetricCodes,aggregationRequired:b.aggregationRequired,minimize:b.minimize,pseudonymize:b.pseudonymize,exportAllowed:b.exportAllowed,auditRequired:b.auditRequired,version:b.version},requestId);return json({success:true,policy});}catch(e){return fail(e);}});
  router.get('/api/platform/admin/notification-governance',async({request,env})=>{try{await requirePlatformAdministrator(request,env);return json({success:true,...await getNotificationGovernance(env)});}catch(e){return fail(e);}});
  router.patch(/^\/api\/platform\/admin\/notification-governance\/(?<policyId>\d+)$/,async({request,env,params,requestId})=>{try{const actor=await requirePlatformAdministrator(request,env);const b=await readJson(request);const policy=await updateNotificationPolicy(env,actor,Number(params.policyId),{purposeCode:b.purposeCode,classification:b.classification,retentionPolicyCode:b.retentionPolicyCode,allowedRecipientRoles:b.allowedRecipientRoles,maxTitleLength:b.maxTitleLength,maxBodyLength:b.maxBodyLength,minimize:b.minimize,auditRequired:b.auditRequired,version:b.version},requestId);return json({success:true,policy});}catch(e){return fail(e);}});
  router.get('/api/platform/admin/external-provider-governance',async({request,env})=>{try{await requirePlatformAdministrator(request,env);return json({success:true,...await getExternalProviderGovernance(env)});}catch(e){return fail(e);}});
  router.patch(/^\/api\/platform\/admin\/external-provider-governance\/(?<policyId>\d+)$/,async({request,env,params,requestId})=>{try{const actor=await requirePlatformAdministrator(request,env);const b=await readJson(request);const policy=await updateExternalProviderPolicy(env,actor,Number(params.policyId),b,requestId);return json({success:true,policy});}catch(e){return fail(e);}});
  router.get('/api/platform/admin/backup-recovery-governance',async({request,env})=>{try{await requirePlatformAdministrator(request,env);return json({success:true,...await getBackupRecoveryGovernance(env)});}catch(e){return fail(e);}});
  router.post('/api/platform/admin/backup-recovery-governance/recovery-points',async({request,env,requestId})=>{try{const actor=await requirePlatformAdministrator(request,env);const b=await readJson(request);const point=await recordBackupRecoveryPoint(env,{backupCode:b.backupCode,companyId:b.companyId,countryCode:b.countryCode,classification:b.classification,dataFields:b.dataFields,authorizationScope:'backup_creation',authorizationGranted:true,operation:'backup_creation',recoveryPointId:b.recoveryPointId,providerObjectRef:b.providerObjectRef,sourceScope:b.sourceScope,sourceDataVersion:b.sourceDataVersion,capturedAt:b.capturedAt,expiresAt:b.expiresAt,integrityHash:b.integrityHash,integrityVerified:b.integrityVerified,sizeBytes:b.sizeBytes,recoveryTestStatus:b.recoveryTestStatus,legalHoldActive:b.legalHoldActive});await auditAdminControl(env,{actor,action:'admin.backup-recovery-point.recorded',resourceType:'backup_recovery_point',resourceId:point?.id||null,targetCompanyId:b.companyId||null,requestId,metadata:{backupCode:b.backupCode,sourceScope:b.sourceScope,integrityVerified:b.integrityVerified!==false}});return json({success:true,recoveryPoint:point},201);}catch(e){return fail(e);}});
  router.post('/api/platform/admin/backup-recovery-governance/restore-requests',async({request,env,requestId})=>{try{const actor=await requirePlatformAdministrator(request,env);const b=await readJson(request);const item=await createBackupRestoreRequest(env,{recoveryPointId:b.recoveryPointId,companyId:b.companyId,targetScope:b.targetScope,reason:b.reason,requestedByRole:actor.role||'platform_administrator',requestedById:actor.id||null,authorizationGranted:b.authorizationGranted===true,legalHoldActive:b.legalHoldActive===true});await auditAdminControl(env,{actor,action:'admin.backup-restore.requested',resourceType:'backup_restore_request',resourceId:item?.id||null,targetCompanyId:b.companyId||null,requestId,metadata:{targetScope:b.targetScope,authorizationGranted:b.authorizationGranted===true}});return json({success:true,restoreRequest:item},201);}catch(e){return fail(e);}});
  router.patch(/^\/api\/platform\/admin\/backup-recovery-governance\/restore-requests\/(?<requestIdParam>[^/]+)\/execution$/,async({request,env,params,requestId})=>{try{const actor=await requirePlatformAdministrator(request,env);const b=await readJson(request);const item=await recordBackupRestoreExecution(env,{requestId:params.requestIdParam,executionStatus:b.executionStatus,providerExecutionRef:b.providerExecutionRef,errorCode:b.errorCode});await auditAdminControl(env,{actor,action:'admin.backup-restore.execution-updated',resourceType:'backup_restore_request',resourceId:item?.id||null,targetCompanyId:item?.company_id||null,requestId,metadata:{executionStatus:b.executionStatus}});return json({success:true,restoreRequest:item});}catch(e){return fail(e);}});
  router.post('/api/platform/admin/backup-recovery-governance/reconciliation',async({request,env,requestId})=>{try{const actor=await requirePlatformAdministrator(request,env);const b=await readJson(request);const item=await reconcileBackupRecoveryPoint(env,b);await auditAdminControl(env,{actor,action:'admin.backup.reconciliation.recorded',resourceType:'backup_reconciliation',resourceId:item?.id||null,targetCompanyId:b.companyId||null,requestId,metadata:{decision:b.decision}});return json({success:true,reconciliation:item},201);}catch(e){return fail(e);}});
}
