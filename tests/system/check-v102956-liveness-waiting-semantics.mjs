import assert from 'node:assert/strict';
import fs from 'node:fs';
import {buildOperationalReadinessContract,validateOperationalReadinessContract} from '../../src/worker/extensions/operations-context/operational-readiness.contract.js';
import {buildCanonicalOperatorIntent,validateCanonicalOperatorIntent} from '../../src/worker/extensions/operations-context/canonical-operator-intent.contract.js';
const root=new URL('../..',import.meta.url).pathname;
const readinessSource=fs.readFileSync(`${root}/src/worker/extensions/operations-context/operational-readiness.contract.js`,'utf8');
const intentSource=fs.readFileSync(`${root}/src/worker/extensions/operations-context/canonical-operator-intent.contract.js`,'utf8');
assert.ok(readinessSource.includes('LIVENESS_WAITING_STATES'));
assert.ok(readinessSource.includes('actualWaiting'));
assert.ok(readinessSource.includes('responsibility:Object.freeze'));
assert.ok(readinessSource.includes('inactive_waiting_has_condition'));
assert.ok(intentSource.includes('actualWaiting'));
assert.ok(intentSource.includes('state="WAIT"'));
assert.ok(intentSource.indexOf('else if(actualWaiting)') < intentSource.indexOf('else if(nextLabel&&responsibleName&&supportActions.length)'));
assert.ok(!intentSource.includes('else if(nextLabel&&responsibleName){state="WAIT"'));

const base={mission:{id:1,status:'Pending'},flow:{terminal:false,next:{action:{code:'assign_driver',label:'Assign Driver'},actor:{type:'tenant',id:9,name:'Aca'}},readiness:{state:'READY',summary:'The mission can continue.'}},liveness:{state:'ACTIONABLE',responsibleActor:{type:'tenant',id:9,name:'Aca'}}};
const actionable=buildOperationalReadinessContract(base);
assert.equal(actionable.liveness.state,'ACTIONABLE');
assert.equal(actionable.waiting.isActive,false);
assert.equal(actionable.waitingFor,null);
assert.equal(actionable.unblock.condition,null);
assert.equal(actionable.waiting.actor,null);
assert.deepEqual(validateOperationalReadinessContract(actionable),[]);
const intent=buildCanonicalOperatorIntent({mission:base.mission,responsibility:{responsible:{type:'TENANT',id:9,name:'Aca',established:true},viewer:{canExecute:false}},readiness:actionable,availableActions:[{code:'check_assignment',label:'Check Assignment'}]});
assert.equal(intent.state,'SUPPORT');
assert.equal(intent.canonical.waiting.isActive,false);
assert.deepEqual(validateCanonicalOperatorIntent(intent),[]);

const waiting=buildOperationalReadinessContract({mission:{id:2,status:'Pending'},flow:{terminal:false,next:{action:{code:'confirm_arrival',label:'Confirm Arrival'},actor:{type:'driver',id:45,name:'wahid'},waitingFor:'wahid'},readiness:{state:'READY',summary:'Ready when the actor progresses.'}},liveness:{state:'WAITING',reasonCode:'awaiting_actor',actor:'wahid',responsibleActor:{type:'driver',id:45,name:'wahid'}}});
assert.equal(waiting.waiting.isActive,true);
assert.equal(waiting.waitingFor,'wahid');
assert.equal(waiting.waiting.actor.name,'wahid');
assert.equal(waiting.unblock.condition.code,'awaiting_actor');
assert.deepEqual(validateOperationalReadinessContract(waiting),[]);
const waitingIntent=buildCanonicalOperatorIntent({mission:{id:2},responsibility:{responsible:{type:'DRIVER',id:45,name:'wahid',established:true},viewer:{canExecute:false}},readiness:waiting,availableActions:[{code:'message',label:'Message'}]});
assert.equal(waitingIntent.state,'WAIT');
assert.match(waitingIntent.label,/Wait for wahid/);
assert.equal(waitingIntent.canonical.waiting.isActive,true);
assert.deepEqual(validateCanonicalOperatorIntent(waitingIntent),[]);
console.log('10.29.56 canonical liveness & waiting semantics gate: PASS');
