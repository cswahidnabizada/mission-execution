import assert from 'node:assert/strict';
import fs from 'node:fs';
import {buildCanonicalActionExecutionBridge,validateCanonicalActionExecutionBridge} from '../../src/worker/extensions/operations-context/canonical-action-execution-bridge.contract.js';
import {buildCanonicalCapabilityExposure} from '../../src/worker/extensions/operations-context/canonical-capability-exposure.contract.js';
const root=new URL('../..',import.meta.url).pathname;
const mission={id:239,status:'Pending',state_version:1};
const flow={missionId:239,status:'Pending',terminal:false,next:{action:{code:'assign_driver',label:'Assign Driver'},viewerCanExecute:true,reasonCode:'assignment_required'}};
const available=[{code:'assign_driver',label:'Assign Driver',target:{kind:'ui',intent:'open_assignment',refresh:'actions'}}];
const capability=buildCanonicalCapabilityExposure({mission,flow,session:{role:'admin'},availableActions:available});
assert.equal(capability.exposureState,'EXECUTABLE');
const bridge=buildCanonicalActionExecutionBridge({mission,flow,session:{role:'admin'},canonicalCapability:capability,availableActions:available});
assert.equal(bridge.state,'EXECUTABLE');
assert.equal(bridge.code,'assign_driver');
assert.equal(bridge.target.intent,'open_assignment');
assert.equal(bridge.viewerCanExecute,true);
assert.deepEqual(validateCanonicalActionExecutionBridge(bridge),[]);
const missing=buildCanonicalActionExecutionBridge({mission,flow,session:{role:'admin'},flow:{...flow,next:{...flow.next,viewerCanExecute:false}},canonicalCapability:{...capability,exposureState:'REQUIRES_VALIDATION',action:null},availableActions:[]});
assert.equal(missing.state,'NOT_EXPOSED');
assert.deepEqual(validateCanonicalActionExecutionBridge(missing),[]);
const js=fs.readFileSync(`${root}/public/assets/js/extensions/dashboard-work-surface-102950.js`,'utf8');
assert.ok(js.includes('const primaryButton=$("#newWorkbenchBody").querySelector("[data-new-primary-action]")'));
assert.ok(!js.includes('unifiedActions.find(a=>a.code===b.dataset.newPrimaryAction)'));
for(const token of ['canonicalActionExecutionBridge','EXECUTABLE','NOT_EXPOSED','REQUIRES_VALIDATION','open_assignment']) assert.ok(js.includes(token),`missing UI bridge token ${token}`);
console.log('10.29.50 canonical action execution bridge gate: PASS');
