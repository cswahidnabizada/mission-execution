import fs from 'node:fs';
import assert from 'node:assert/strict';
const version=fs.readFileSync('VERSION','utf8').trim();
const pkg=JSON.parse(fs.readFileSync('package.json','utf8'));
const routes=fs.readFileSync('src/worker/modules/admin-control/objective-orchestrator.routes.js','utf8');
const ui=fs.readFileSync('public/assets/js/frontend/admin/command-center.js','utf8');
const release=fs.readFileSync('RELEASE.md','utf8');
const [major,minor,patch]=version.split('.').map(Number);
assert.ok(major>16||(major===16&&(minor>10||(minor===10&&patch>=23))),'candidate must preserve gap intelligence');
assert.ok(pkg.version.localeCompare('16.10.23', undefined, {numeric:true})>=0, 'package must preserve 23 objective capability');
assert.match(routes,/objective-runs\/:runId\/gaps/,'gap assessment must use the objective run');
assert.match(routes,/getPlatformCommandCenter\(env,plan\.scope\|\|\{\}\)/,'gaps must use fresh canonical context');
assert.match(routes,/CANONICAL_AUTHORITY_UNAVAILABLE/,'unavailable authorities must be explicit blockers');
assert.match(routes,/SUCCESS_CRITERION_UNVERIFIED/,'unverified criteria must remain gaps');
assert.match(routes,/REQUIRED_EVIDENCE/,'missing evidence must be represented');
assert.match(routes,/OBJECTIVE_GAPS_ASSESSED/,'assessment must be evented');
assert.match(routes,/completionAllowed:false/,'gap count must never imply objective completion');
assert.match(routes,/OBJECTIVE_RUN_REVISION_CONFLICT/,'stale assessments must be rejected');
assert.match(ui,/objectiveAssessGaps/,'Command Center must let Super Admin calculate remaining work');
assert.match(ui,/CALCULATE REMAINING WORK/,'gap assessment action must be explicit');
assert.match(ui,/GAP &amp; DEPENDENCY INTELLIGENCE/,'gap ledger must be presented');
