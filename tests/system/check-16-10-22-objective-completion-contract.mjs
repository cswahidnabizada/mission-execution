import fs from 'node:fs';
import assert from 'node:assert/strict';
const version=fs.readFileSync('VERSION','utf8').trim();
const pkg=JSON.parse(fs.readFileSync('package.json','utf8'));
const routes=fs.readFileSync('src/worker/modules/admin-control/objective-orchestrator.routes.js','utf8');
const ui=fs.readFileSync('public/assets/js/frontend/admin/command-center.js','utf8');
const release=fs.readFileSync('RELEASE.md','utf8');
const [major,minor,patch]=version.split('.').map(Number);
assert.ok(major>16||(major===16&&(minor>10||(minor===10&&patch>=22))),'candidate must preserve completion contract');
assert.ok(pkg.version.localeCompare('16.10.22', undefined, {numeric:true})>=0, 'package must preserve 22 objective capability');
assert.match(routes,/completionContract:\{schemaVersion:1,status:'DRAFT'/,'new objectives must start with an explicit unconfirmed contract');
assert.match(routes,/objective-runs\/:runId\/contract/,'contract must be saved through a protected objective route');
assert.match(routes,/OBJECTIVE_COMPLETION_CONTRACT_INVALID/,'invalid or incomplete criteria must be rejected');
assert.match(routes,/OBJECTIVE_COMPLETION_CONTRACT_CONFIRMED/,'contract confirmation must be append-only evented');
assert.match(routes,/OBJECTIVE_COMPLETION_CONTRACT_REQUIRED/,'execution must be blocked until contract confirmation');
assert.match(routes,/ALL_CRITERIA_REQUIRE_INDEPENDENT_EVIDENCE/,'completion policy must require evidence for every criterion');
assert.match(routes,/OBJECTIVE_RUN_REVISION_CONFLICT/,'stale contract updates must be rejected');
assert.match(ui,/objectiveContractForm/,'Command Center must expose contract definition');
assert.match(ui,/CONFIRM COMPLETION CONTRACT/,'confirmation must be explicit');
assert.match(ui,/Required evidence \(one per line\)/,'UI must request evidence requirements');
assert.match(ui,/scopeConfirmed:true/,'objective scope must be explicitly confirmed');
assert.match(release,/# Mission Execution 16\.10\.22/);
console.log('16.10.22 Objective Completion Contract: PASS');
