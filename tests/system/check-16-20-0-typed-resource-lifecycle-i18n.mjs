import fs from 'node:fs';
import assert from 'node:assert/strict';
import {listReusableDataDefinitions} from '../../src/worker/security/platform-reusable-data.service.js';
import {validatePlatformConfiguration} from '../../src/worker/security/platform-configuration.service.js';
const read=p=>fs.readFileSync(p,'utf8');
const defs=listReusableDataDefinitions();
const lifecycle=defs.find(x=>x.entryType==='sector_lifecycle');
const translations=defs.find(x=>x.entryType==='translation_bundle');
assert.ok(lifecycle,'sector lifecycle must be a governed reusable asset');
assert.ok(translations,'translation bundle must be a governed reusable asset');
assert.equal(lifecycle.authority,'platformConfigurationAuthority');
assert.equal(translations.authority,'platformConfigurationAuthority');
assert.equal(lifecycle.fieldSchemas.states.type,'json');
assert.equal(lifecycle.fieldSchemas.transitions.type,'json');
assert.equal(lifecycle.fieldSchemas.sectorCode.type,'relationship');
assert.equal(translations.fieldSchemas.translations.type,'json');
assert.equal(translations.fieldSchemas.direction.type,'enum');
assert.equal(validatePlatformConfiguration({domainCode:'mission.lifecycle',configKey:'sector.logistics.lifecycle.delivery',version:'1',payload:{states:[],transitions:[]}}).domainCode,'mission.lifecycle');
assert.equal(validatePlatformConfiguration({domainCode:'i18n.catalog',configKey:'locale.en.base',version:'1',payload:{translations:{'common.cancel':'Cancel'}}}).domainCode,'i18n.catalog');
const ui=read('public/assets/js/frontend/admin/resource-management.js');
assert.match(ui,/schema\.type==='boolean'/);
assert.match(ui,/schema\.type==='integer'/);
assert.match(ui,/schema\.type==='enum'/);
assert.match(ui,/schema\.type==='json'/);
assert.match(ui,/CHECK IMPACT/);
assert.match(ui,/resource-management\/\$\{encodeURIComponent\(r\.type\)\}\/\$\{encodeURIComponent\(r\.id\)\}\/impact/);
const reusable=read('src/worker/security/platform-reusable-data.service.js');
assert.match(reusable,/SECTOR_LIFECYCLE_TRANSITION_INVALID/);
assert.match(reusable,/TRANSLATION_ENTRY_INVALID/);
assert.match(reusable,/createConfigurationDraft/);
const entry=read('src/worker/security/platform-data-entry.service.js');
assert.match(entry,/DATA_ENTRY_\$\{key\.toUpperCase\(\)\}_BOOLEAN_REQUIRED/);
const routes=read('src/worker/modules/admin-control/admin-build-data.routes.js');
assert.match(routes,/resource-management.*impact/);
assert.match(routes,/getResourceExplorer\(env,\{resourceType,resourceId\}\)/,'resource detail reads must use the canonical service argument contract');
assert.match(entry,/DATA_ENTRY_SECTOR_LIFECYCLE_TRANSITION_INVALID/);
assert.match(entry,/FALLBACK_LANGUAGE_NOT_FOUND/);
const explorer=read('src/worker/security/platform-resource-explorer.service.js');
assert.match(explorer,/domain_code='mission\.lifecycle'/);
assert.match(explorer,/domain_code='i18n\.catalog'/);
assert.match(explorer,/defines_lifecycle/);
console.log('16.20.0 Typed Resource Schemas, Sector Lifecycle, Translation Bundles and Impact Preview: PASS');
