import fs from 'node:fs';
import assert from 'node:assert/strict';
const version=fs.readFileSync('VERSION','utf8').trim();
const pkg=JSON.parse(fs.readFileSync('package.json','utf8'));
const routes=fs.readFileSync('src/worker/modules/admin-control/objective-orchestrator.routes.js','utf8');
const ui=fs.readFileSync('public/assets/js/frontend/admin/command-center.js','utf8');
const release=fs.readFileSync('RELEASE.md','utf8');
const [major,minor,patch]=version.split('.').map(Number);
assert.ok(major>16||(major===16&&(minor>10||(minor===10&&patch>=26))),'candidate must preserve outcome/recovery loop');
assert.ok(pkg.version.localeCompare('16.10.26', undefined, {numeric:true})>=0, 'package must preserve 26 objective capability');
assert.match(routes,/objective-runs\/:runId\/outcome\/reconcile/,'outcome reconciliation must be objective-run scoped');
assert.match(routes,/WAITING_FOR_VERIFIED_EVIDENCE/,'missing evidence must remain waiting');
assert.match(routes,/RECOVERY_REQUIRED/,'failed/uncertain effects must trigger recovery planning');
assert.match(routes,/canonical_verification/,'only trusted canonical verification may satisfy evidence');
assert.match(routes,/automaticRetry:false/,'recovery must not blindly retry');
assert.match(routes,/completionAllowed:false/,'reconciliation must not auto-complete the objective');
assert.match(routes,/OBJECTIVE_OUTCOME_RECONCILED/,'outcome reconciliation must be evented');
assert.match(ui,/objectiveReconcileOutcome/,'Command Center must expose outcome reconciliation');
assert.match(ui,/RECONCILE OUTCOME &amp; RECOVERY/,'reconciliation must be explicit');
assert.match(release,/# Mission Execution 16\.10\.26/);
console.log('16.10.26 Outcome & Recovery Loop: PASS');
