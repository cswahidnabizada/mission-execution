assert.match(app,/canonicalLayoutContext\('executor-workspace'/);
assert.match(app,/renderComponent,STUDIO_RENDERER_VERSION/);
assert.match(app,/await renderMissionWorkbench\(workspace,id,action\)/);
assert.match(appHtml,new RegExp(`mission-executor-layout-context\\.css\\?v=${pkg.version.replaceAll('.','\\.')}`));
