import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const pkg=JSON.parse(read('package.json'));
const version=read('VERSION').trim();
const service=read('src/worker/modules/admin-control/product-publisher-semantic-configuration.service.js');
const contract=read('src/worker/modules/admin-control/product-contract.service.js');
const orch=read('src/worker/modules/admin-control/product-publisher-orchestrator.service.js');
const context=read('src/worker/modules/admin-control/admin-route-context.js');
const ui=read('public/assets/js/frontend/admin/product-publisher.js');
const css=read('public/assets/css/admin-control.css');
const assert=(ok,msg)=>{if(!ok)throw new Error(msg)};
assert(/^\d+\.\d+\.\d+$/.test(version),`release version is ${version}`);
assert(pkg.version===version,'package version mismatch');
for(const x of ['getProductPublisherSemanticConfiguration','semanticConfigurationPayload','capabilities:catalog','roles:action_policy'])assert(service.includes(x),`semantic configuration authority mapping missing ${x}`);
assert(contract.includes("contractVersion:'product-contract.v1'")&&contract.includes('contractHash'),'Product Contract authority was not carried forward');
assert(orch.includes('semanticConfiguration'),'Publisher workspace does not expose semantic configuration');
assert(context.includes('getProductPublisherSemanticConfiguration'),'admin context does not expose semantic configuration');
for(const x of ['Configure the product in product language','data-semantic-capability','data-semantic-role','ADVANCED · RAW CANONICAL CONFIGURATION'])assert(ui.includes(x),`semantic Publisher UI missing ${x}`);
for(const x of ['publisher-semantic-grid','publisher-role-card','publisher-semantic-option'])assert(css.includes(x),`semantic Publisher styling missing ${x}`);
assert(!ui.includes('CSS.escape('),'semantic role binding must not depend on CSS.escape');
console.log('10.53.0 Semantic Publisher configuration gate: PASS');
