import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd(); const checks=[];
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
function ok(name,cond){checks.push([name,!!cond]);}
const svc=read('src/worker/extensions/mission-planning/mission-planning-authority.service.js');
const evalSvc=read('src/worker/extensions/mission-planning/mission-plan-evaluation-authority.service.js');
const mig=read('database/migrations/0145_governed_mission_planning.sql');
const migNext=read('database/migrations/0146_governed_plan_evaluation.sql');
const coord=read('src/worker/extensions/mission-execution-coordinator/mission-execution-coordinator.service.js');
const contract=read('src/worker/extensions/mission-execution-coordinator/mission-execution-coordinator.contract.js');
const routes=read('src/worker/extensions/mission-execution-coordinator/mission-execution-coordinator.routes.js');
ok('version',svc.includes("MISSION_PLANNING_AUTHORITY_VERSION='14.0.0'"));
ok('canonical_plan_table',mig.includes('CREATE TABLE IF NOT EXISTS mission_plans'));
ok('unique_plan_key',mig.includes('plan_key TEXT NOT NULL UNIQUE'));
ok('planning_contract',mig.includes("WHERE capability_code='planning'"));
ok('non_executing',svc.includes("execution:{allowed:false,reason:'PLANNING_IS_NON_EXECUTING'}"));
ok('canonical_revalidation',svc.includes('canonicalRevalidationRequired:true'));
ok('context_hash',svc.includes('contextHash'));
ok('plan_hash',svc.includes('planHash'));
ok('idempotency',svc.includes('idempotent:true'));
ok('no_duplicate_planner',svc.includes("planAgentMission"));
ok('coordinator_plan_gate',coord.includes("createMissionPlan(env"));
ok('coordinator_contract',contract.includes('planningContracted'));
ok('plan_routes',routes.includes('/plan') && routes.includes('/plans'));
ok('accept_route',routes.includes('acceptMissionPlan') && routes.includes('MISSION_PLAN_ACCEPT_UNAVAILABLE'));
ok('evaluation_authority',evalSvc.includes("MISSION_PLAN_EVALUATION_AUTHORITY_VERSION='14.0.0'"));
ok('evaluation_table',migNext.includes('CREATE TABLE IF NOT EXISTS mission_plan_evaluations'));
ok('evaluation_before_acceptance',svc.includes('evaluationAllowsAcceptance'));
ok('execution_requires_acceptance',coord.includes('MISSION_PLAN_NOT_ACCEPTED'));
ok('architecture_layer',!svc.includes("from '../core/canonical-db.js'") && svc.includes("from '../../core/canonical-db.js'"));
ok('action_catalog_lower_layer',routes.includes('mission-plan-evaluation-authority.service.js')); 
const failed=checks.filter(x=>!x[1]);
console.log(`13.7.0 Governed Mission Planning: ${failed.length?'FAIL':'PASS'} (${checks.length} checks)`);
for(const [n,c] of checks)console.log(`${c?'PASS':'FAIL'} ${n}`);
if(failed.length)process.exit(1);
