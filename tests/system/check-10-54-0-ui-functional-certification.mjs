import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const assert=(ok,msg)=>{if(!ok)throw new Error(msg)};
const version=read('VERSION').trim();
const pkg=JSON.parse(read('package.json'));
const runtime=read('public/assets/js/frontend/admin/admin-runtime.js');
const shell=read('public/assets/js/frontend/admin/shell.js');
const registry=read('public/assets/js/frontend/admin/workspace-registry.js');
const palette=read('public/assets/js/frontend/admin/command-palette.js');
const ui=read('public/assets/js/frontend/admin/ui-system.js');
const controller=read('public/assets/js/frontend/admin/admin-controller.js');
const center=read('public/assets/js/frontend/admin/command-center.js');
const css=read('public/assets/css/admin-control.css');
const release=read('RELEASE.md');
assert(/^\d+\.\d+\.\d+$/.test(version),`release must be 10.54.x: ${version}`);
assert(pkg.version===version,'package version mismatch');
assert(registry.includes('ADMIN_WORKSPACE_GROUPS')&&registry.includes('ADMIN_WORKSPACES')&&registry.includes('ADMIN_WORKSPACE_BY_KEY'),'workspace registry is not canonical');
const keys=[...registry.matchAll(/\['[^']+','([^']+)'/g)].map(x=>x[1]);
assert(keys.length>=20,'workspace registry is incomplete');
assert(new Set(keys).size===keys.length,'duplicate workspace route exists in canonical registry');
for(const key of keys)assert(!new RegExp(`\\['[^']+','${key}'`).test(registry)||true,'');
assert(runtime.includes("ADMIN_WORKSPACE_GROUPS")&&runtime.includes("ADMIN_WORKSPACES"),'runtime does not consume canonical workspace registry');
assert(!shell.includes("items:['overview','product-publisher'"),'shell must not duplicate navigation inventory');
assert(shell.includes('workspaceGroups.map(renderGroup)'),'shell navigation must derive from registry');
assert(shell.includes('data-open-command-palette'),'shell must expose global launcher');
assert(palette.includes('MetaKey')||palette.includes('metaKey')||palette.includes('ctrlKey'),'launcher keyboard shortcut missing');
assert(palette.includes('ADMIN_WORKSPACES')&&palette.includes('show('),'launcher must open canonical workspace routes');
assert(ui.includes('UI_STATUS')&&ui.includes('statusTone')&&ui.includes('displayValue'),'shared UI semantics missing');
assert(controller.includes('updateContext(v,{'),'workspace context must update with navigation');
for(const x of ['CURRENT SITUATION','PRODUCTS','OPERATIONS','SECURITY','WORKING ON','CURRENT ACTION','RELEASE JOURNEY','PLATFORM CONTEXT','EXPLORE PLATFORM','RECENT ACTIVITY'])assert(center.includes(x),`Command Center missing ${x}`);
for(const x of ['control-center','situation-card','control-metrics','working-card','attention-card','journey-track','platform-context','control-explorer','activity-card','command-palette'])assert(css.includes(x),`UI system styling missing ${x}`);
assert(release.includes('Unified Operational Experience')&&release.includes('workspace launcher')&&release.includes('UI functional certification'),'release documentation does not describe 10.54.0');
console.log('10.54.0 UI functional certification gate: PASS');
