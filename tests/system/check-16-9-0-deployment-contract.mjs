import assert from 'node:assert/strict';
import fs from 'node:fs';
const pkg=JSON.parse(fs.readFileSync('package.json','utf8'));
const lock=JSON.parse(fs.readFileSync('package-lock.json','utf8'));
const version=fs.readFileSync('VERSION','utf8').trim();
const npmrc=fs.readFileSync('.npmrc','utf8');
const build=fs.readFileSync('scripts/check-build-environment.mjs','utf8');
const docs=fs.readFileSync('docs/16.9.0-DEPLOYMENT-CONTRACT.md','utf8');
assert.equal(version,'16.10.13','canonical VERSION must be 16.10.13');
assert.equal(pkg.version,version);
assert.equal(lock.version,version);
assert.equal(lock.packages[''].version,version);
assert.equal(pkg.engines.node,'24.x');
assert.equal(pkg.engines.npm,'>=10 <12');
assert.equal(pkg.packageManager,'npm@10.9.2');
assert.match(npmrc,/engine-strict=true/);
assert.match(pkg.scripts['deploy:production'],/npm run build.*npm run check:release.*npm run check:production-certification.*npm run migrate:production.*wrangler deploy/);
assert.equal(pkg.scripts.deploy,'npm run deploy:production','deploy alias must use the single governed production path');
assert.match(pkg.scripts.build,/check-build-environment\.mjs/);
assert.match(build,/nodeMajor!==24/);
assert.match(build,/\[10,11\]\.includes\(npmMajor\)/);
assert.match(pkg.scripts['check:release'],/check-16-9-0-deployment-contract\.mjs/);
for(const command of ['deploy:development','certify:development','migrate:development','dev']) assert.equal(pkg.scripts[command],undefined,`development-only script must be absent: ${command}`);
assert.equal(fs.existsSync('scripts/deploy-development.mjs'),false);
assert.equal(fs.existsSync('scripts/apply-development-migrations.mjs'),false);
assert.equal(fs.existsSync('docs/16.9.4-DEVELOPMENT-DEPLOYMENT.md'),false);
assert.match(docs,/npm run deploy:production/);
assert.match(docs,/npm run deploy:production/);
const onboarding=fs.readFileSync('src/worker/modules/onboarding/organization-onboarding.service.js','utf8');
const fixtureService=fs.readFileSync('src/worker/modules/admin-control/certification-environment.service.js','utf8');
assert.match(onboarding,/certificationFixture && actor\?\.type!==['"]platform_super_administrator['"]/);
assert.match(onboarding,/if\(!certificationFixture\)/);
assert.match(fixtureService,/certificationFixture:true/);
console.log('Production-only deployment contract: PASS (16.10.10; development deployment logic removed)');
