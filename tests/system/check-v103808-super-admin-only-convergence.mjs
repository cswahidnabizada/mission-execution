import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=p=>fs.readFileSync(p,'utf8');
const pkg=JSON.parse(read('package.json'));
assert.equal(read('VERSION').trim(),'10.38.12');
assert.equal(pkg.version,'10.38.12');
const admin=read('src/worker/modules/admin-control/admin-control.routes.js');
const platformAdmin=read('src/worker/security/platform-administrator.js');
const verification=read('src/worker/modules/verification/verification.routes.js');
const security=read('src/worker/security/request-security.js');
const frontend=read('public/assets/js/frontend/admin/admin.js');
assert(!admin.includes('platform_reviewer'),'admin login must not create reviewer sessions');
assert(!admin.includes('PLATFORM_REVIEW_SECRET'),'admin login must not use reviewer secret');
assert(!admin.includes('onmission_platform_reviewer'),'admin control must not issue reviewer cookie');
assert(!platformAdmin.includes('platform-review-session'),'platform administrator must not import reviewer authority');
assert(!platformAdmin.includes('requireReviewer'),'platform administrator must not use reviewer authority');
assert(!verification.includes('PLATFORM_REVIEW_SECRET'),'verification routes must not use reviewer secret');
assert(!verification.includes('onmission_platform_reviewer'),'verification routes must not use reviewer cookie');
assert(verification.includes('requirePlatformSuperAdministrator'),'verification routes must require Super Admin');
assert(security.includes('onmission_platform_super_admin'),'mutation security must bind Super Admin cookie');
assert(!security.includes('onmission_platform_reviewer'),'mutation security must not reference reviewer cookie');
assert(!fs.existsSync('src/worker/security/platform-review-session.js'),'legacy reviewer session module must be removed');
assert(!fs.existsSync('public/assets/js/pages/platform-review.js'),'legacy reviewer frontend must be removed');
assert(!fs.existsSync('public/platform-review.html'),'legacy reviewer page must be removed');
assert(frontend.includes('/api/platform/access/admin/login'),'canonical Super Admin login must remain');
assert(frontend.includes('/api/platform/admin/super-admin/session'),'Studio must verify Super Admin directly');
console.log('10.38.12 Super Admin-only platform control convergence: PASS');
