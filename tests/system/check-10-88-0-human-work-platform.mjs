assert.match(app,/human-work-model\.js/,'application runtime must consume the human work model');
assert.match(app,/focusMission\(model\)/,'Today must use canonical focus rather than a local dashboard score');
assert.match(app,/renderMissionWorkbench\(workspace,id,action\)/,'work selection must converge on canonical Mission Workspace');
assert.match(app,/dmc:back/,'Mission Workspace back navigation must return to the unified work surface');
