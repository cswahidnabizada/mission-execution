import assert from 'node:assert/strict';
import fs from 'node:fs';
import {simulate} from '../../public/assets/js/frontend/admin/simulation-engine.js';
import {replaySimulation} from '../../public/assets/js/frontend/admin/simulation-replay.js';
import {buildSimulationPlan,SIMULATION_PLANNER_CONTRACT} from '../../public/assets/js/frontend/admin/simulation-planner-adapter.js';
const run=simulate({scenarioId:'failed-delivery',executor:'virtual-van',missionId:'SIM-DE-DELIVERY-001',deadline:60,seed:'stable-seed-42',resources:{availableCapacity:1}});
assert.equal(run.schema,'onmission.simulation-run.v1');
assert.equal(run.scenarioVersion,'1');
assert.equal(run.simulationOnly,true);
assert.equal(run.productionMutation,false);
assert.equal(run.deviceCommandSent,false);
assert.equal(run.outcomeComparison.expected,'RECOVERY_VERIFIED');
assert.equal(run.outcomeComparison.observed,'RECOVERY_VERIFIED');
assert.equal(run.outcomeComparison.match,true);
assert.equal(run.simulationPlan.contract.planningAuthorityVersion,'14.0.0');
assert.equal(run.simulationPlan.execution.allowed,false);
const replay=replaySimulation(run);
assert.equal(replay.match,true);
assert.equal(replay.expectedFingerprint,replay.observedFingerprint);
assert.equal(replay.productionMutation,false);
assert.equal(replay.deviceCommandSent,false);
const blocked=buildSimulationPlan({scenarioId:'normal',executorId:'virtual-van',deadlineMinutes:20,seed:'x',resources:{requiredMinutes:28,requiredCapacity:2,availableCapacity:1}});
assert.equal(blocked.status,'BLOCKED');
assert.equal(blocked.steps.length,0);
assert.equal(blocked.execution.allowed,false);
const mismatch=structuredClone(run);mismatch.journey[0].detail='tampered trace';
assert.equal(replaySimulation(mismatch).match,false);
assert.throws(()=>replaySimulation({schema:'wrong',simulationOnly:true}),/SIMULATION_REPLAY_INPUT_INVALID/);
const ui=fs.readFileSync('public/assets/js/frontend/admin/simulation-lab.js','utf8');
const page=fs.readFileSync('public/simulator.html','utf8');
assert.match(ui,/replaySimulation\(lastRun\)/);
assert.match(page,/id="replaySimulation"/);
assert.match(page,/id="replaySeed"/);
assert.match(page,/id="availableCapacity"/);
assert.equal(SIMULATION_PLANNER_CONTRACT.executionAllowed,false);
console.log('16.10.74 canonical planning adapter + deterministic replay: PASS');
