import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {readFileSync} from 'node:fs';
import {ADMIN_WORKSPACE_KEYS} from '../../public/assets/js/frontend/admin/workspace-registry.js';
import {CONTROL_PLANE_AREAS,searchControlPlaneAreas,validateControlPlaneModel} from '../../public/assets/js/frontend/admin/control-plane-model.js';

const model=validateControlPlaneModel(ADMIN_WORKSPACE_KEYS);
assert.equal(model.valid,true,model.errors.join('; '));
assert.equal(model.areaCount,6,'Super Admin must expose six consolidated top-level areas');
assert.equal(new Set(CONTROL_PLANE_AREAS.map(x=>x.key)).size,6,'area keys must be unique');
assert.ok(searchControlPlaneAreas('Germany').some(x=>x.key==='markets'),'Germany market search should route to Market Operations');
assert.ok(searchControlPlaneAreas('ChatGPT').some(x=>x.key==='ai'),'AI provider search should route to AI & Integrations');
assert.ok(searchControlPlaneAreas('onboarding').some(x=>x.key==='markets'),'market onboarding search should route to Markets');
assert.ok(searchControlPlaneAreas('database').some(x=>x.key==='ai'),'database search should route to AI & Integrations');
assert.equal(searchControlPlaneAreas('not-a-real-capability').length,0,'unknown search should not fabricate a workspace');
assert.equal(searchControlPlaneAreas('').length,6,'empty query should expose all six areas');
const source=await readFile(new URL('../../public/assets/js/frontend/admin/command-center.js',import.meta.url),'utf8');
assert.doesNotMatch(source,/controlPlaneAreaSearch|control-explorer/,'Control Center must not duplicate primary workspace navigation');
assert.match(source,/Market preparation and launch objectives belong in the single Market Operations workspace/,'market work is consolidated outside the platform objective composer');
const controller=await readFile(new URL('../../public/assets/js/frontend/admin/admin-controller.js',import.meta.url),'utf8');
assert.match(controller,/resource-management/,'platform resources must use canonical Resource Management workspace');
assert.match(source,/product-publisher/,'market launch must use canonical Market Factory workspace');
assert.match(readFileSync('public/assets/js/frontend/admin/shell.js','utf8'),/Server authorization remains authoritative/,'shell must preserve server-side authorization boundary');
console.log('PASS 16.10.86 unified Control Plane: six areas, canonical route coverage and navigation convergence');
