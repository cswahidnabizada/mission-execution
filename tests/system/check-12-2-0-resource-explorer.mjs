import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const assert=(ok,msg)=>{if(!ok)throw new Error(msg)};
const service=read('src/worker/security/platform-resource-explorer.service.js');
const routes=read('src/worker/modules/admin-control/super-admin-operating-system.routes.js');
const context=read('src/worker/modules/admin-control/admin-route-context.js');
const palette=read('public/assets/js/frontend/admin/command-palette.js');
const explorer=read('public/assets/js/frontend/admin/resource-explorer.js');
const css=read('public/assets/css/admin-control.css');
const recovery=read('src/worker/modules/transitions/transition-reconciliation.routes.js');
const version=read('VERSION').trim();
assert(/^(?:12\.(2|3|4|5|6|7|8|9)\.\d+|13\.\d+\.\d+|14\.\d+\.\d+|16\.\d+\.\d+)$/.test(version),`Resource Explorer continuity requires 12.2.x–12.9.x; got ${version}`);
for(const t of ['searchResourceExplorer','getResourceExplorer','tenantGraph','userGraph','mutationBoundary'])assert(service.includes(t),`resource explorer service missing ${t}`);
for(const t of ['/api/platform/admin/resource-search','resource-explorer'])assert(routes.includes(t),`resource explorer route missing ${t}`);
assert(context.includes('platform-resource-explorer.service.js'),'resource explorer authority must be exported through admin route context');
assert(palette.includes("openResourceExplorer"),'single command search must open Resource Explorer');
for(const t of ['DEPENDENCY GRAPH','MANAGE','TRASH','PURGE','Canonical authorities'])assert(explorer.includes(t),`Resource Explorer UI missing ${t}`);
assert(css.includes('.admin-resource-explorer')&&css.includes('.resource-graph-svg'),'Resource Explorer styling missing');
assert(recovery.includes('requirePlatformAdministrator')&&recovery.includes('requirePlatformSuperAdminStepUp'),'Super Admin recovery boundary missing');
assert(recovery.includes("WHERE status='processing' AND mutation_phase IN ('uncertain','event_committed')"),'Super Admin recovery list must inspect platform-wide processing transitions');
console.log(`${version} Unified Super Admin Resource Explorer + Recovery Boundary continuity: PASS`);
