import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=p=>fs.readFileSync(p,'utf8');
const pkg=JSON.parse(read('package.json'));
const manifest=JSON.parse(read('RELEASE-MANIFEST.json'));
const ui=read('public/assets/js/frontend/admin/market-factory.js');
const css=read('public/assets/css/frontend/admin.css');
const release=read('RELEASE.md');
assert.equal(pkg.version,'16.23.0');
assert.equal(manifest.version,'16.23.0');
assert.equal(manifest.baseVersion,'16.21.0');
for(const token of ['Market Launch Studio','Prepare a market in one form','mfGuidedPrepare','CREATE STAGED MARKET PACKAGE','Advanced intake','Governed markets','NO IMPLICIT TRUST'])assert.ok(ui.includes(token),`missing studio UI token: ${token}`);
for(const token of ['countryName','countryIso','productKey','sectorCode','jurisdiction','region','currency','missionLifecycle','humanRoles','onboarding','missionWorkspace','defaultLayout','aiProvider','microsoft365','cloudProvider'])assert.ok(ui.includes(token),`missing guided field/requirement: ${token}`);
assert.ok(ui.includes("ensureStepUp('POST:/api/platform/admin/market-factory/import')"),'guided import must use existing step-up protection');
assert.ok(ui.includes("'/api/platform/admin/market-factory/import'"),'guided import must use canonical Market Factory intake');
assert.ok(ui.includes('allSelectionsRequireCanonicalAuthorityVerification:true'),'staged selections must remain unverified requirements');
assert.ok(ui.includes('No live market was activated'),'UI must be explicit that staging is not activation');
assert.ok(css.includes('.mf-studio-steps')&&css.includes('@media(max-width:560px)'),'responsive studio styles missing');
assert.ok(release.includes('16.17.0 — Market Cleanup and Guided Intake'),'release note missing');
console.log('PASS 16.16.0 Unified Market Launch Studio contract');
