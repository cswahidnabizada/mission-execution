import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const app=read('src/worker/app.js');
const route=read('src/worker/extensions/action-execution/secured-action-execution.routes.js');
const contract=read('src/worker/extensions/action-execution/secured-action-execution.contract.js');
const client=read('public/assets/js/extensions/secured-action-execution-101938.js');
const work=read('public/assets/js/extensions/dashboard-work-surface-101938.js');
const html=read('public/admin.html');
const pkg=JSON.parse(read('package.json'));
const failures=[];
const must=(s,needle,label)=>{if(!s.includes(needle))failures.push(`${label}:missing ${needle}`)};
must(app,'registerSecuredActionExecutionRoutes','app registration');
must(app,'registerSecuredActionExecutionRoutes(router);','route registration');
must(route,'requireSession','secured route authentication');
must(route,'getForSession','tenant-scoped mission lookup');
must(route,'unifiedActionForMission','authoritative action context');
must(route,'serviceDefinition','service map validation');
must(route,'x-mission-state-token','fresh state token');
must(contract,'stale_state_token','stale-state rejection');
must(contract,'delegatedToSecuredService:true','final authority delegation');
must(contract,'advisory:false','execution preparation is not intelligence');
must(client,'/api/secured-actions/missions/${missionId}/prepare','client preflight');
must(client,'X-Mission-State-Token','client state token forwarding');
must(client,'preconditions?.ready','client blocks unready execution');
must(client,'executeSecuredActionTarget','existing service execution path preserved');
must(work,'secured-action-execution-101938.js','Work uses secured execution foundation');
must(html,'dashboard-work-surface-101938.css','current dashboard CSS');
must(html,'dashboard-work-surface-101938.js','current dashboard JS');
if(pkg.version!=='10.19.38')failures.push(`package version ${pkg.version}`);
if(!pkg.scripts?.['check:10.19.38'])failures.push('missing check:10.19.38');
const release=fs.readdirSync(root).filter(x=>/^RELEASE-.*\.md$/.test(x));
if(release.length!==1||release[0]!=='RELEASE-10.19.38.md')failures.push(`release files: ${release.join(', ')}`);
if(read('VERSION').trim()!=='10.19.38')failures.push('VERSION mismatch');
if(failures.length){console.error('FAIL');for(const f of failures)console.error(`- ${f}`);process.exit(1)}
console.log('PASS — 10.19.38 secured action execution foundation');
