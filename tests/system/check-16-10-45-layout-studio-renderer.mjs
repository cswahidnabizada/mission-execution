import fs from 'node:fs';
import assert from 'node:assert/strict';
import { COMPONENT_RENDERERS, renderComponent, renderPage, STUDIO_RENDERER_VERSION } from '../../public/assets/js/frontend/admin/layout-studio-renderer.js';
const pkg=JSON.parse(fs.readFileSync('package.json','utf8'));
const client=fs.readFileSync('public/assets/js/frontend/admin/layout-studio.js','utf8');
const html=fs.readFileSync('public/layout-studio.html','utf8');
const routes=fs.readFileSync('src/worker/modules/admin-control/layout-studio.routes.js','utf8');
assert.ok(pkg.version.localeCompare('16.10.45', undefined, {numeric:true})>=0);
assert.equal(STUDIO_RENDERER_VERSION,pkg.version);
assert.equal(Object.keys(COMPONENT_RENDERERS).length,15);
for(const type of Object.keys(COMPONENT_RENDERERS)) assert.ok(renderComponent({id:'test-item',type,properties:{label:'Safe label',title:'Safe title',description:'Safe description'}}).includes('Safe'));
assert.match(renderComponent({id:'x',type:'hero',properties:{title:'<script>alert(1)</script>'}}),/&lt;script&gt;/);
assert.doesNotMatch(renderComponent({id:'x',type:'hero',properties:{title:'<script>alert(1)</script>'}}),/<script>/);
assert.match(renderComponent({id:'x',type:'not-approved'}),/Unsupported component type/);
assert.match(renderPage({id:'home',componentIds:['hero','missing']},[{id:'hero',type:'hero',properties:{title:'Hello'}}]),/Missing component reference/);
assert.match(client,/renderPage/);
assert.match(client,new RegExp('layout-studio-renderer\\.js\\?v='+pkg.version.replaceAll('.','\\.')));
assert.match(routes,new RegExp('rendererContractVersion:\''+pkg.version+'\''));
assert.match(routes,/productionRouteBindings:0/);
assert.match(html,new RegExp('v='+pkg.version.replaceAll('.','\\.')));
console.log('16.10.46 canonical Studio renderer contract: PASS');
