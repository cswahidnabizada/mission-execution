import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const version=read('VERSION').trim();
const versionParts=version.split('.').map(Number);
const minimumParts=[10,89,0];
const firstDifference=versionParts.findIndex((part,index)=>part!==minimumParts[index]);
const isAtLeastMinimum=versionParts.length===3&&versionParts.every(Number.isInteger)&&(firstDifference===-1||versionParts[firstDifference]>minimumParts[firstDifference]);
assert.ok(isAtLeastMinimum,`human working expansion continuity requires 10.89.0 or newer, got ${version}`);
const app=read('public/assets/js/frontend/app/app.js');
const roleModel=read('public/assets/js/frontend/work/role-work-model.js');
const css=read('public/assets/css/frontend/human-work.css');
const publisher=read('public/assets/js/frontend/admin/product-publisher.js');
const adminCss=read('public/assets/css/admin-control.css');
assert.match(app,/loadExecutorWorkContext/,'executor work must compose the canonical executor operational authority');
assert.match(app,/loadCompanyOperationsContext|COMPANY OPERATIONS/,'company operations must be represented in the human work surface');
assert.match(app,/\/api\/network\/invitations/,'network collaboration must consume the governed invitation authority');
assert.match(app,/executeCanonicalObjectAction\(action==='accept'\?'accept_trust':'reject_trust'/,'network trust decisions must use the canonical Action Registry client');
assert.match(app,/executeCanonicalObjectAction\(action==='accept'\?'accept_network':'reject_network'/,'mission collaboration decisions must use the canonical Action Registry client');
assert.match(app,/\/api\/(driver|executor)\/me\/operational/,'executor operational status must use the existing canonical operational endpoint');
assert.match(roleModel,/\/api\/executor\/me\/operational/,'executor role model missing executor authority');
assert.match(roleModel,/\/api\/driver\/me\/operational/,'legacy driver compatibility path missing');
assert.match(roleModel,/\/api\/network\/invitations/,'executor context must expose network invitations');
assert.match(css,/\.executor-work-panel/,'executor work presentation missing');
assert.match(css,/\.company-operations-panel/,'company operations presentation missing');
assert.match(css,/\.hwp-collab-card/,'network collaboration decision presentation missing');
assert.match(publisher,/function humanFactoryWork\(w\)/,'Product Factory needs a human next-decision projection');
assert.match(publisher,/PRODUCT WORK/,'Product Factory human work label missing');
assert.match(publisher,/w\.next/,'Product Factory human work must use canonical next-action projection');
assert.match(adminCss,/\.product-factory-human-work/,'Product Factory human work styling missing');
assert.doesNotMatch(roleModel,/fetch\(/,'role work model must use the canonical API client');
assert.doesNotMatch(app,/api\(['"]\/api\/[^'"`]+\/(delete|cancel|assign)/,'human work surfaces must not invent direct domain mutation paths');
console.log(`10.89.0 Human Working Platform Expansion continuity: PASS (${version})`);
