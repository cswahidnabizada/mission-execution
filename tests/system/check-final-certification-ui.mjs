import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const version=fs.readFileSync(path.join(root,'VERSION'),'utf8').trim();
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const assert=(ok,msg)=>{if(!ok)throw new Error(msg)};
const runtime=read('public/assets/js/frontend/admin/admin-runtime.js');
const registry=read('public/assets/js/frontend/admin/workspace-registry.js');
const admin=read('public/assets/js/frontend/admin/admin.js');
const legacy=read('public/assets/js/frontend/admin/oversight-panels.js');
const certificationComposition=read('public/assets/js/frontend/admin/surfaces/control.js');
const shell=read('public/assets/js/frontend/admin/shell.js');
const ui=read('public/assets/js/frontend/admin/certification.js');
const css=read('public/assets/css/admin-control.css');
assert(registry.includes("['Certification','certification'"),'Certification must be a registered administrative workspace');
assert(admin.includes('panel-registry.js'),'Certification UI must be loaded through the Admin panel registry');
assert(certificationComposition.includes(`../certification.js?v=${version}`),'Certification UI must have a versioned module import in the CONTROL surface');
assert(certificationComposition.includes("certification:()=>renderCertification({api,esc,show:navigate})"),'Certification renderer must be registered with the controller and receive UI dependencies');
assert(shell.includes('workspaceGroups.map(renderGroup)'),'Admin shell must render canonical navigation inventory');
for(const token of ['STATIC','SCHEMA','INTEGRATION','ADVERSARIAL','REAL JOURNEY','RECOVERY'])assert(ui.includes(token),`Certification UI missing ${token} evidence class`);
for(const token of ['No evidence = no certification','Cross-tenant access must be rejected','Retries must remain idempotent','Interrupted work must surface recovery state'])assert(ui.includes(token),`Certification UI missing rule: ${token}`);
assert(ui.includes("status==='unavailable'"),'Authority-unavailable state must not be inferred as certification');
assert(ui.includes('No certification state is inferred'),'UI must explicitly distinguish authority failure from certification state');
assert(css.includes('.cert-evidence-grid')&&css.includes('.cert-flow'),'Certification UI must have dedicated responsive presentation logic');
console.log('Final certification UI convergence gate: PASS');
