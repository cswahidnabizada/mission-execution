import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const failures=[];
const ok=(v,m)=>{if(!v)failures.push(m)};
const version=read('VERSION').trim();
const release32=read('tests/fixtures/release-history/RELEASE-10.32.0.md');
const pkg=JSON.parse(read('package.json'));
const schema=read('database/schema.current.sql');
const build=read('build.sh');
const migrations=fs.readdirSync(path.join(root,'database/migrations')).filter(x=>x.endsWith('.sql')).sort();
ok(release32.includes('# ON Mission 10.32.0'),'10.32.0 protected release record remains intact');
ok(fs.existsSync(path.join(root,'tests/fixtures/release-history/RELEASE-10.31.99.md')),'10.31.99 protected baseline record remains');
ok(pkg.version===version,'package version matches VERSION');
ok(!fs.existsSync(path.join(root,'database/schema.sql')),'obsolete schema.sql is removed');
ok(fs.existsSync(path.join(root,'database/schema.current.sql')),'current schema snapshot exists');
ok(migrations.includes('0064_database_release_governance.sql'),'0064 protected migration remains present');
ok(migrations.slice(0,64).at(-1)==='0064_database_release_governance.sql','protected migration chain through 0064 remains ordered');
ok(migrations.length>=64,'current migration chain preserves the protected 64-migration history');
ok(schema.includes('CREATE TABLE plans'), 'subscription plan foundation is represented in current schema');
ok(schema.includes('CREATE TABLE subscriptions'), 'subscription record foundation is represented in current schema');
ok(!schema.includes('CREATE TABLE usage_counters'), 'obsolete usage counter table is excluded from canonical current schema');
ok(/CREATE TABLE\s+(?:\"|')?subscription_policies(?:\"|')?/i.test(schema), 'subscription policy schema is represented');
ok(schema.includes('CREATE TABLE operational_access_leases'), 'operational access lease schema is represented');
ok(schema.includes('CREATE TABLE activation_review_requests'), 'activation review schema is represented');
ok(build.includes('check-migration-contract.mjs')&&build.includes('check-schema-current.mjs')&&build.includes('check-release-engineering.mjs'),'build uses deterministic release checks');
ok(!build.includes('/mnt/data/rebuild')&&!build.includes('/mnt/data/work_')&&!build.includes('10.19.x'),'historical build paths/reconstruction logic are absent');
ok(fs.existsSync(path.join(root,'RELEASE-MANIFEST.json')),'release manifest exists');
if(failures.length){console.error(`10.32.0 release engineering regression: FAIL (${failures.length})`);for(const f of failures)console.error(`- ${f}`);process.exit(1)}
console.log('10.31.99 database & release engineering protected regression: PASS');
