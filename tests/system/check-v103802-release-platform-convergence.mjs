import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const assert=(ok,msg)=>{if(!ok)throw new Error(msg)};
const version=read('VERSION').trim();
const pkg=JSON.parse(read('package.json'));
assert(version===pkg.version,`VERSION=${version} package=${pkg.version}`);
assert(pkg.version===version,'package.json version mismatch');
assert(fs.existsSync(path.join(root,'public/assets/js/frontend/admin/admin.js')),'canonical Platform Control implementation missing');
assert(!fs.existsSync(path.join(root,'public/assets/js/pages/admin-control.js')),'legacy Platform Control implementation still exists');
const admin=read('public/assets/js/frontend/admin/admin.js');
const adminIndex=read('public/platform/access/admin/index.html');
const login=read('public/login.html');
for(const token of ['function configTable(','function safeSectionRender(','/platform/access/admin/','Platform Configuration Center','System Health','/api/platform/access/admin/login']) assert(admin.includes(token),`canonical Platform Control missing: ${token}`);
assert(admin.includes('SIGN IN AS SUPER ADMIN')||admin.includes('ELEVATE SUPER ADMIN'),'canonical Platform Control must provide a Super Admin authentication path');
assert(adminIndex.includes(`/assets/js/frontend/admin/admin.js?v=${version}`),'hidden platform entry does not use canonical frontend implementation');
assert(login.includes(`/assets/js/pages/access.js?v=${version}`),'sign-in is not on current release');
assert(!login.includes('/admin/'),'public sign-in must not expose platform entry');
const obsolete=['public/assets/js/pages/admin.js','public/assets/js/pages/role-workspace.js','public/assets/js/pages/canonical-role-workspace.js','public/assets/js/pages/my-driver.js','public/assets/js/pages/missions.js','public/assets/js/pages/tenant-marketplace.js','public/assets/js/pages/admin-control.js'];
for(const p of obsolete)assert(!fs.existsSync(path.join(root,p)),`obsolete frontend implementation still exists: ${p}`);
const active=[];function walk(dir){for(const name of fs.readdirSync(dir)){const p=path.join(dir,name),st=fs.statSync(p);if(st.isDirectory())walk(p);else if(/\.(js|html)$/.test(name))active.push(fs.readFileSync(p,'utf8'));}}
walk(path.join(root,'public'));
const joined=active.join('\n');
assert(!joined.includes('/admin.html#'),'legacy admin operational references remain in public frontend');
assert(!joined.includes('/driver/dashboard.html#mission'),'legacy executor mission references remain in public frontend');
assert(!joined.includes('10.37.12'),'stale 10.37.12 runtime asset identity remains in active frontend');
console.log(`${version} release platform convergence: PASS`);
