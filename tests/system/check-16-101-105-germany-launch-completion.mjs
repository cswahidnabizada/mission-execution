import assert from 'node:assert/strict';
import { buildMarketLaunchControl } from '../../src/worker/security/market-launch-control.service.js';
import { assessControlledMarketLaunch } from '../../src/worker/security/controlled-market-launch-certification.js';
const task=(key,status='TODO',extra={})=>({key,title:key,status,...extra});
const input={market:{status:'DRAFT',packageStatus:'DRAFT'},workbench:{marketStatus:'DRAFT',packageStatus:'DRAFT',onboardingStatus:'CLOSED',tasks:[task('resources:one','COMPLETE',{evidence:{summary:'Canonical resource was read back',evidenceRef:'resource-123'}}),task('legal:terms')],preview:{operations:[{operation:'CREATE'},{operation:'REUSE'},{operation:'UPDATE'}],conflicts:[],safeToApply:false}}};
const result=buildMarketLaunchControl(input);
assert.equal(result.readOnly,true);
assert.equal(result.status,'WAITING_FOR_USER');
assert.equal(result.nextAction.taskKey,'legal:terms','verified tasks must be skipped');
assert.equal(result.nextAction.mode,'REQUEST_INPUT_OR_REVIEW');
assert.equal(result.preparation.create,1);
assert.equal(result.preparation.reuse,1);
assert.equal(result.preparation.review,1);
assert.ok(result.externalDependencies.some(x=>x.key==='legal:terms'));
assert.equal(result.missionProof.cases.length,8);
assert.ok(result.missionProof.cases.every(x=>x.status==='EVIDENCE_REQUIRED'));
assert.equal(result.releaseGates.length,8);
const unavailable=buildMarketLaunchControl({...input,authorityHealth:{status:'DEGRADED',unavailable:['mission_authority']}});
assert.equal(unavailable.status,'WAITING_CANONICAL_AUTHORITY');
const conflict=buildMarketLaunchControl({...input,workbench:{...input.workbench,preview:{conflicts:[{id:1}],safeToApply:false}}});
assert.equal(conflict.status,'BLOCKED');
const validProof={};
for(const c of ['tenant-isolation','authorization','assignment','execution','effects','independent-verification','failure-containment','recovery']) validProof[c]={verified:true,evidenceRef:`proof-${c}-123`,observedAt:'2026-11-11T12:00:00Z',source:'independent-test-run'};
const falseReady=buildMarketLaunchControl({market:{status:'LIVE',packageStatus:'LIVE'},workbench:{tasks:[task('mission-journey','COMPLETE',{evidence:{proofCases:validProof}})],onboardingMode:'INVITE_ONLY'},runtimeEvidence:null});
assert.notEqual(falseReady.status,'COMPLETE','market status and user-submitted proof claims must not certify proof');
assert.ok(falseReady.missionProof.cases.every(x=>x.status==='EVIDENCE_REQUIRED'),'user-editable task evidence must not satisfy trusted runtime proof');
const completeTasks=[task('legal:terms','COMPLETE',{evidence:{summary:'Reviewed by named counsel; decision recorded',evidenceRef:'legal-review-123'}}),task('mission-journey','COMPLETE',{evidence:{summary:'Mission test case references attached',evidenceRef:'mission-proof-123'}}),task('runtime-certification','COMPLETE',{evidence:{summary:'Runtime controls verified',evidenceRef:'runtime-cert-123'}})];
const complete=buildMarketLaunchControl({market:{status:'LIVE',packageStatus:'LIVE'},workbench:{tasks:completeTasks,onboardingMode:'INVITE_ONLY',publicationOperation:{status:'COMPLETED',stage:'LIVE'},preview:{resources:[],conflicts:[],safeToApply:true}},runtimeEvidence:{verified:true,source:'runtime-certifier',observedAt:'2026-11-11T12:00:00Z',proofCases:validProof}});
assert.equal(complete.status,'COMPLETE','a fully evidenced live market, release and invite-only onboarding can be certified');
assert.ok(complete.releaseGates.every(g=>['COMPLETE','EVIDENCE_ATTACHED'].includes(g.status)));
const wrapper=assessControlledMarketLaunch(input);
assert.ok(wrapper.launchControl);
assert.equal(wrapper.readOnly,true);
const fs=await import('node:fs');
const route=fs.readFileSync('src/worker/modules/admin-control/admin-build-data.routes.js','utf8');
const ui=fs.readFileSync('public/assets/js/frontend/admin/market-factory.js','utf8');
assert.match(route,/assessControlledMarketLaunch/);
assert.match(ui,/missionProof\?\.cases/);
assert.match(ui,/data-next-task-key/);
console.log('16.101–16.105 Germany launch control and proof gates: PASS');
