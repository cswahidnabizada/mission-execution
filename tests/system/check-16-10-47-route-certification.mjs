import fs from 'node:fs';
import assert from 'node:assert/strict';
const pkg=JSON.parse(fs.readFileSync('package.json','utf8'));
const manifest=JSON.parse(fs.readFileSync('RELEASE-MANIFEST.json','utf8'));
const html=fs.readFileSync('public/layout-studio.html','utf8');
const client=fs.readFileSync('public/assets/js/frontend/admin/layout-studio.js','utf8');
const routes=fs.readFileSync('src/worker/modules/admin-control/layout-studio.routes.js','utf8');
const renderer=fs.readFileSync('public/assets/js/frontend/admin/layout-studio-renderer.js','utf8');
assert.ok(pkg.version.localeCompare('16.10.47', undefined, {numeric:true})>=0);
assert.equal(manifest.version,pkg.version);
assert.ok(manifest.base);
assert.match(html,new RegExp('v='+pkg.version.replaceAll('.','\\.')));
assert.match(client,/Production routes/);
assert.match(client,/\/api\/platform\/admin\/layout-studio\/certification/);
assert.match(client,/routeCertificationMarkup/);
assert.match(routes,/layout-studio\/certification/);
assert.match(routes,/requirePlatformAdministrator\(request,env\)/);
assert.match(routes,/rendererParity:'NOT_TESTED'/);
assert.match(routes,/publicationEnabled:false/);
assert.match(routes,/PRODUCTION_RENDERER_BINDINGS_NOT_CERTIFIED/);
assert.match(renderer,new RegExp("STUDIO_RENDERER_VERSION = '"+pkg.version+"'"));
const registry=routes.match(/const EXPERIENCE_REGISTRY=\[(.*?)\n\];/s)?.[1]||'';
const sourcePages=[...registry.matchAll(/sourcePage:'([^']+)'/g)].map(x=>x[1]);
assert.ok(sourcePages.length>=5,'expected explicit source-mapped route inventory');
for(const source of sourcePages) assert.ok(fs.existsSync(source),`route source missing: ${source}`);
assert.match(pkg.scripts['check:release'],/check-16-10-47-route-certification\.mjs/);
console.log('16.10.47+ production route certification compatibility contract: PASS');
