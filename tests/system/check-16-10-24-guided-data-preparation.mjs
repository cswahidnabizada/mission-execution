import fs from 'node:fs';
import assert from 'node:assert/strict';
const version=fs.readFileSync('VERSION','utf8').trim();
const pkg=JSON.parse(fs.readFileSync('package.json','utf8'));
const routes=fs.readFileSync('src/worker/modules/admin-control/objective-orchestrator.routes.js','utf8');
const ui=fs.readFileSync('public/assets/js/frontend/admin/command-center.js','utf8');
const release=fs.readFileSync('RELEASE.md','utf8');
const [major,minor,patch]=version.split('.').map(Number);
assert.ok(major>16||(major===16&&(minor>10||(minor===10&&patch>=24))),'candidate must preserve guided preparation');
assert.ok(pkg.version.localeCompare('16.10.24', undefined, {numeric:true})>=0, 'package must preserve 24 objective capability');
assert.match(routes,/objective-runs\/:runId\/preparations/,'preparation proposals must be tied to a run');
assert.match(routes,/OBJECTIVE_PREPARATION_INVALID/,'invalid preparation must be rejected');
assert.match(routes,/OBJECTIVE_GAPS_NOT_ASSESSED/,'preparation must require a fresh gap assessment');
assert.match(routes,/OBJECTIVE_RESOURCE_REUSE_NOT_CANONICAL/,'reuse must reference an observed canonical resource');
assert.match(routes,/PREPARED_PENDING_CANONICAL_VERIFICATION/,'prepared data must not imply verified truth');
assert.match(routes,/canonicalMutationPerformed:false/,'preparation must not mutate domain authorities');
assert.match(routes,/OBJECTIVE_DATA_PREPARATION_RECORDED/,'preparation must be evented');
assert.match(ui,/data-objective-preparation/,'actual discovered gaps must generate contextual forms');
assert.match(ui,/VALIDATE &amp; PREPARE PROPOSAL/,'preparation must be an explicit action');
assert.match(release,/# Mission Execution 16\.10\.24/);
console.log('16.10.24 Guided Data Preparation: PASS');
