import assert from 'node:assert/strict';
import fs from 'node:fs';
import {buildCanonicalResponsibility,validateCanonicalResponsibility} from '../../src/worker/extensions/operations-context/canonical-responsibility.contract.js';
import {buildCanonicalCapabilityExposure} from '../../src/worker/extensions/operations-context/canonical-capability-exposure.contract.js';
const root=new URL('../..',import.meta.url).pathname;
const base={id:251,status:'Pending',company_id:7,driver_id:45,driver_name:'wahid',state_version:2};
const assignment={driverId:45,driverName:'wahid',executorId:null,executorName:null};
const flow={missionId:251,status:'Pending',terminal:false,next:{action:{code:'confirm_arrival',label:'Confirm Arrival'},actor:{type:'driver',id:45,name:'wahid'},viewerCanExecute:false,waitingFor:'wahid',reasonCode:'execution_actor_progress'}};
const r=buildCanonicalResponsibility({mission:base,assignment,flow,session:{role:'admin',tenantId:7}});
assert.equal(r.responsible.type,'DRIVER'); assert.equal(r.responsible.id,45); assert.equal(r.responsible.name,'wahid');
assert.equal(r.next.actor.id,45); assert.equal(r.next.actorMatchesResponsibility,true); assert.equal(r.viewer.canExecute,false);
assert.deepEqual(validateCanonicalResponsibility(r),[]);
const cap=buildCanonicalCapabilityExposure({mission:base,flow,session:{role:'admin'},availableActions:[]});
assert.equal(cap.code,'confirm_arrival'); assert.equal(cap.exposureState,'NOT_EXPOSED');
const js=fs.readFileSync(`${root}/public/assets/js/extensions/dashboard-work-surface-102951.js`,'utf8');
for(const token of ['canonicalResponsibility','Responsible actor','Responsibility type','Viewer execution','Canonical execution','Canonical next step']) assert.ok(js.includes(token),`missing convergence token ${token}`);
assert.ok(js.includes('m.executor_name||"—"'),'executor display must not fall back to driver');
assert.ok(!js.includes('m.executor_name||m.driver_name||assignment.driver_name'),'legacy executor fallback remains');
const route=fs.readFileSync(`${root}/src/worker/extensions/operations-context/operations-context.routes.js`,'utf8');
assert.ok(route.includes('buildCanonicalResponsibility'));
assert.ok(route.includes('canonicalResponsibility'));
console.log('10.29.51 responsibility & convergence gate: PASS');
