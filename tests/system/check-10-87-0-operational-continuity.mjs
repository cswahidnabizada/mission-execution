import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import {assessCanonicalMissionLiveness,validateCanonicalMissionLiveness} from "../../src/worker/core/canonical-liveness-registry.js";
const root=process.cwd();
const read=f=>fs.readFileSync(path.join(root,f),"utf8");
const version=read("VERSION").trim();
assert.match(version,/^(?:10\.(8[7-9]|9\d)|(?:11\.0[23456789]|(?:11\.1[0-8]|12\.[0-9]+|13\.[0-9]+|14\.[0-9]+|15\.[0-9]+|16\.[0-9]+)))\./,"operational continuity gate must remain in the post-10.87 release lineage");
const posture=read("src/worker/modules/transitions/transition-recovery-posture.service.js");
const coordinator=read("src/worker/extensions/engine-coordinator/engine-coordinator.service.js");
const liveness=read("src/worker/core/canonical-liveness-registry.js");
const contract=read("src/worker/extensions/engine-coordinator/engine-coordination.contract.js");
const context=read("src/worker/extensions/operations-context/operations-context.routes.js");
