assert.match(contract,/recovery:Object\.freeze/);
assert.match(context,/recovery:Object\.freeze/);
assert.match(adaptive,/recoveryRequired/);
assert.match(adaptive,/A previous mission action needs canonical recovery/);
assert.match(adaptive,/if\(recoveryRequired\)return "AT RISK"/);
