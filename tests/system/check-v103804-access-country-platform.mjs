import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const assert=(ok,msg)=>{if(!ok)throw new Error(msg)};
const pkg=JSON.parse(read('package.json'));
assert(/^10\.38\.12$/.test(read('VERSION').trim()),'VERSION must be the current 10.38.12 release');
assert(pkg.version==='10.38.12','package.json must be the current 10.38.12 release');
const situation=read('src/worker/security/user-situation.service.js');
assert(situation.includes("import {resolveCanonicalComplianceContext} from './compliance-context.service.js';"),'canonical compliance context import missing');
const auth=read('src/worker/modules/auth/auth.routes.js');
assert(auth.includes("FROM country_product_launches l JOIN country_catalog c"),'user login must be gated by an active country launch');
assert(auth.includes('SESSION_LOGOUT_AUTHORITY_BYPASS'),'logout must remain available during session-authority failure');
const shell=read('public/assets/js/frontend/shell/app-shell.js');
assert(shell.includes('id="logoutWorkspace"'),'workspace runtime error must provide sign out');
assert(shell.includes('href="/"'),'workspace runtime error must provide home navigation');
const picker=read('public/assets/js/core/country-picker.js');
assert(!picker.includes('const FALLBACK='),'country picker must not expose unlaunched fallback countries');
assert(picker.includes('No country is currently available'),'country picker must close registration when no country is launched');
const landing=read('public/assets/js/frontend/public/landing.js');
assert(landing.includes("a.status!=='start'"),'public landing must close user access when no country is active');
const login=read('public/login.html');
assert(!login.includes('/admin/'),'public sign-in must not expose platform access');
const admin=read('public/assets/js/frontend/admin/admin.js');
assert(admin.includes("/api/platform/access/admin/login"),'platform access must use dedicated admin login endpoint');
assert(admin.includes("/platform/access/admin/"),'platform studio must converge on hidden platform access path');
assert(admin.includes("/api/platform/admin/super-admin/session"),'platform studio must restore Super Admin elevation');
assert(fs.existsSync(path.join(root,'public/platform/access/admin/index.html')),'hidden platform access page missing');
assert(!fs.existsSync(path.join(root,'public/admin/index.html')) || read('public/admin/index.html').includes("location.replace(\"/\")"),'legacy /admin must not remain a platform login surface');
const routes=read('src/worker/modules/admin-control/admin-control.routes.js');
assert(routes.includes("/api/platform/access/admin/login"),'dedicated platform access login route missing');
assert(routes.includes('PLATFORM_SUPER_ADMIN_SECRET'),'platform access must be protected by infrastructure secret');
assert(routes.includes('/api/platform/admin/super-admin/session'),'Super Admin session endpoint missing');
const executor=read('public/assets/js/pages/executor-register.js');
assert(executor.includes('/api/product/availability'),'executor registration must enforce country product availability');
const execPage=read('public/driver/index.html');
assert(execPage.includes('COUNTRY-GOVERNED EXECUTOR ACCESS'),'executor registration must use the canonical product structure');
console.log('10.38.12 access, country launch and platform access convergence: PASS');
