import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const version=read('VERSION').trim();
const pkg=JSON.parse(read('package.json'));
const trash=read('src/worker/security/platform-trash.service.js');
const control=read('src/worker/security/platform-data-control.service.js');
const routes=read('src/worker/modules/admin-control/admin-build-data.routes.js');
const ui=read('public/assets/js/frontend/admin/data-governance.js');
const migration=read('database/migrations/0114_platform_lifecycle_purge_hardening.sql');
const assert=(ok,msg)=>{if(!ok)throw new Error(msg)};
assert(/^\d+\.\d+\.\d+$/.test(version),`current lifecycle release must be 10.58.x: ${version}`);
assert(pkg.version===version,'package version mismatch');
assert(trash.includes('COALESCE(cmp.updated_at,c.created_at) updated_at'),'trash candidate discovery must not depend on nonexistent companies.updated_at');
assert(trash.includes("deps.total===0&&looksSample(c.code,c.name)"),'unused country references must not all become cleanup candidates');
for(const token of ['type===\'ui\'||type===\'content\'','type===\'data_entry\'','Permanent deletion blocked','purgeAllTrash'])assert(trash.includes(token),`trash lifecycle missing ${token}`);
for(const token of ['action===\'purge\'','platform_trash_items','permanent:true'])assert(control.includes(token),`data control purge authority missing ${token}`);
for(const route of ['/api/platform/admin/trash/candidates','/api/platform/admin/trash/candidates/bulk','/api/platform/admin/trash/empty','/api/platform/admin/trash','/api/platform/admin/data-control/action'])assert(routes.includes(route),`lifecycle route missing ${route}`);
for(const token of ['ensureStepUp()','DELETE PERMANENTLY','EMPTY TRASH · PURGE SAFE ITEMS','Trash & Recovery'])assert(ui.includes(token),`lifecycle UI missing ${token}`);
assert(migration.includes('ALTER TABLE platform_trash_items RENAME TO platform_trash_items_legacy_1058'),'0114 must preserve existing trash records');
assert(migration.includes('DE_PLATFORM_LIFECYCLE'),'0114 must register lifecycle retention governance');
console.log('10.60.0 Platform Data Lifecycle gate: PASS');
