import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const version=read('VERSION').trim();
const versionAtLeast=(actual,minimum)=>{const a=String(actual).split('.').map(Number),b=String(minimum).split('.').map(Number);if(a.length!==3||b.length!==3||!a.every(Number.isInteger)||!b.every(Number.isInteger))return false;for(let i=0;i<3;i++){if(a[i]!==b[i])return a[i]>b[i];}return true;};
assert.ok(versionAtLeast(version, '10.90.0'),'Wave 1 surface inventory must remain certified through the current release');
const inv=JSON.parse(read('docs/HUMAN-WORK-SURFACE-INVENTORY.json'));
assert.equal(inv.version,'10.90.0','Wave 1 inventory artifact must remain versioned as 10.90.0');
assert.ok(['10.89.0','10.90.0'].includes(inv.base),'Wave 1 inventory must remain based on the protected 10.89/10.90 lineage');
assert.ok(inv.items.length>=24,'inventory must include all discovered HTML surfaces');
const paths=new Set(inv.items.map(x=>x.path));
for(const required of ['public/app/index.html','public/missions.html','public/driver/dashboard.html','public/my-driver/index.html','public/foryou/index.html','public/platform/access/admin/index.html','public/admin.html','public/admin-control.html'])assert.ok(paths.has(required),`missing surface inventory entry: ${required}`);
const html=inv.items.filter(x=>x.surface_type==='HTML');
const actual=[];
function walk(dir){for(const e of fs.readdirSync(path.join(root,dir),{withFileTypes:true})){const p=path.join(dir,e.name);if(e.isDirectory())walk(p);else if(e.name.endsWith('.html'))actual.push(p.replaceAll('\\','/'));}}
walk('public');
assert.equal(new Set(html.map(x=>x.path)).size,actual.length,'every HTML surface must appear exactly once');
for(const f of actual)assert.ok(paths.has(f),`unmapped HTML surface: ${f}`);
const admin=inv.items.filter(x=>x.surface_type==='ADMIN WORKSPACE');
assert.ok(admin.length>=25,'all canonical admin workspaces must be inventoried');
const allowed=new Set(['KEEP / CONTROL PLANE']);
for(const x of admin)assert.ok(allowed.has(x.disposition),`admin workspace cannot drift into tenant work model: ${x.path}`);
assert.match(read('docs/HUMAN-WORK-SURFACE-INVENTORY.md'),/Wave 2 entry criteria/);
assert.match(read('docs/HUMAN-WORK-SURFACE-INVENTORY.md'),/Control Plane remains a separate application boundary/);
assert.match(read('public/assets/js/frontend/navigation/registry.js'),/Today/);
assert.match(read('public/assets/js/frontend/navigation/registry.js'),/Work/);
console.log('10.90.0 Human Work Surface Inventory: PASS');
console.log(`HTML surfaces inventoried: ${html.length}`);
console.log(`Admin workspaces inventoried: ${admin.length}`);
console.log(`Total inventory entries: ${inv.items.length}`);
