import fs from 'node:fs';
import assert from 'node:assert/strict';
import pkg from '../../config/markets/germany-logistics-market.json' with {type:'json'};
import {listOwnerLifecycleAdapters,executeOwnerLifecycleCommand} from '../../src/worker/security/owner-lifecycle-adapters.service.js';
import {ACTION_CODES} from '../../src/worker/application/actions/action-registry.js';
import {validateMarketPackageInput,buildMarketLaunchStageContract,buildMarketProductDefinitionComponents} from '../../src/worker/security/market-factory.service.js';
import {PRODUCT_COMPONENT_TYPES,PRODUCT_DEFINITION_SCHEMAS} from '../../src/worker/security/product-definition.service.js';

assert.equal(pkg.schemaVersion,'1.0');
assert.equal(pkg.packageType,'market-package');
assert.equal(pkg.country.iso,'DE');
assert.equal(pkg.metadata.productKey,'on-mission');
for(const action of pkg.actions)assert.ok(Object.values(ACTION_CODES).includes(action),`action is not present in canonical action registry: ${action}`);
assert.ok(pkg.languages.some(x=>x.code==='de'&&x.primary));
assert.ok(pkg.languages.some(x=>x.code==='en'));
assert.ok(pkg.sectors.some(x=>x.code==='logistics'));
const migrations=fs.readdirSync('database/migrations').filter(x=>x.endsWith('.sql')).map(x=>fs.readFileSync(`database/migrations/${x}`,'utf8')).join('\n');
for(const capability of pkg.capabilities)assert.ok(migrations.includes(`'${capability}'`),`capability is not present in canonical migrations: ${capability}`);
for(const purpose of pkg.governance.retention.map(x=>x.purposeCode))assert.ok(migrations.includes(`'${purpose}'`),`retention purpose is not present in canonical migrations: ${purpose}`);
for(const key of ['de-privacy','en-privacy','de-terms','en-terms','de-imprint','en-imprint','de-consent','en-consent','de-welcome','en-welcome'])assert.ok(pkg.content.some(x=>x.code===key),`missing market content ${key}`);
for(const key of ['privacy-notice','terms-of-service','imprint','cookie-and-analytics','data-processing-agreement','retention-schedule'])assert.ok(pkg.legal.some(x=>x.key===key&&x.required&&x.status!=='reviewed'));
assert.equal(pkg.governance.retention.length>=5,true);
assert.equal(pkg.governance.residency.fallbackAllowed,false);
assert.equal(pkg.execution.physicalActuationEnabled,false);
assert.equal(pkg.certification.status,'NOT_CERTIFIED');
assert.ok(pkg.governance.integrations.some(x=>x.code==='platform-email'&&x.required&&x.providerCode===null));
const integrationContract=buildMarketLaunchStageContract({key:'integration:platform-email',title:'Verify integration: E-Mail and system notifications',category:'integrations',description:'Verify canonical provider'},1);
assert.equal(integrationContract.steps[0].permittedCommand,'integration.inspect');
assert.equal(integrationContract.steps[2].permittedCommand,'integration.verify');
assert.equal(integrationContract.steps[3].permittedCommand,'task.evidence.record');
assert.equal(integrationContract.steps[3].executionMode,'HUMAN_ATTESTATION');
const legalContract=buildMarketLaunchStageContract({key:'legal:privacy-notice',title:'Review privacy notice',category:'legal',description:'Legal review'},1);
assert.equal(legalContract.steps[2].permittedCommand,'market.legal.review');
assert.equal(legalContract.steps[3].executionMode,'HUMAN_ATTESTATION');
const releaseReportContract=buildMarketLaunchStageContract({key:'release-report',title:'Generate final launch report',category:'release',description:'Evidence report'},1);
assert.equal(releaseReportContract.steps.length,2);
assert.equal(releaseReportContract.steps[0].permittedCommand,'canonical.read');
assert.equal(releaseReportContract.steps[1].permittedCommand,'task.evidence.record');
const recoveryContract=buildMarketLaunchStageContract({key:'publication-recovery',title:'Certify publication failure recovery',category:'release',description:'Recovery evidence'},1);
assert.equal(recoveryContract.name,'Recovery');
const sectorContract=buildMarketLaunchStageContract({key:'resource:sector:logistics',title:'Prepare logistics sector',category:'product',description:'Canonical sector'},1);
assert.ok(!sectorContract.steps.some(x=>x.key==='link'));
const reconciliationContract=buildMarketLaunchStageContract({key:'reconciliation',title:'Review canonical reconciliation',category:'platform',description:'Read-only preview'},1);
assert.ok(reconciliationContract.steps.some(x=>x.permittedCommand==='canonical.validate'));
const normalizedPackage=validateMarketPackageInput(pkg);
assert.equal(normalizedPackage.product.productKey,'on-mission');
assert.ok(normalizedPackage.capabilities.includes('mission_truth'));
assert.ok(normalizedPackage.actions.every(action=>Object.values(ACTION_CODES).includes(action)));
assert.ok(normalizedPackage.content.some(x=>x.code==='de-privacy'&&x.pageType==='legal'));
assert.equal(normalizedPackage.regionalPlacement.jurisdictionCode,'EU');
assert.equal(normalizedPackage.regionalPlacement.policyVersion,'regional-placement-v1');
for(const role of pkg.governance.roles)assert.ok(migrations.includes(`'${role.roleCode}'`),`role is not present in canonical role migrations: ${role.roleCode}`);
assert.equal(pkg.governance.onboarding.publicMode,'CLOSED_UNTIL_MARKET_RELEASE_OPEN');
assert.ok(pkg.governance.integrations.some(x=>x.code==='ai-provider'&&x.status==='DISABLED_BY_DEFAULT'));
assert.ok(normalizedPackage.governance.retention.every(x=>!Object.hasOwn(x,'retentionDays')),'unapproved retention periods must remain unspecified, never become zero-day retention');
const productComponents=buildMarketProductDefinitionComponents(pkg,pkg.sectors[0],'on-mission:de:logistics');
assert.deepEqual([...new Set(productComponents.map(x=>x.type))].sort(),[...PRODUCT_COMPONENT_TYPES].sort());
for(const component of productComponents){for(const field of PRODUCT_DEFINITION_SCHEMAS[component.type].required)assert.ok(component.payload[field]!==undefined&&component.payload[field]!==null,`missing ${component.type}.${field}`);}
assert.ok(productComponents.find(x=>x.type==='workflow').payload.transitions.some(x=>x.from==='NEXT SITUATION'&&x.to==='OBSERVE'));
assert.ok(productComponents.find(x=>x.type==='role'&&x.key==='driver').payload.label.includes('Executor'));

