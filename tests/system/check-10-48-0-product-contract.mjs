import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const contract=read('src/worker/modules/admin-control/product-contract.service.js');
const lab=read('src/worker/modules/admin-control/product-test-lab.service.js');
const orch=read('src/worker/modules/admin-control/product-publisher-orchestrator.service.js');
const context=read('src/worker/modules/admin-control/admin-route-context.js');
const ui=read('public/assets/js/frontend/admin/product-publisher.js');
const pkg=JSON.parse(read('package.json'));
const version=read('VERSION').trim();
const assert=(ok,msg)=>{if(!ok)throw new Error(msg)};
assert(/^\d+\.\d+\.\d+$/.test(version),`release version is ${version}`);
assert(pkg.version===version,'package version mismatch');
for(const x of ['getProductContract','contractVersion:\'product-contract.v1\'','contractHash','immutable:true','canonical-composition'])assert(contract.includes(x),`product contract contract missing ${x}`);
assert(orch.includes('getProductContract')&&orch.includes('productContract'),'publisher workspace does not expose Product Contract');
assert(context.includes('getProductContract'),'admin context does not export Product Contract');
for(const x of ['listProductVerificationContracts','journey-contracts','journeys:journeyContracts'])assert(lab.includes(x),`journey Test Lab coverage missing ${x}`);
assert(ui.includes('PRODUCT CONTRACT')&&ui.includes('Immutable release composition')&&ui.includes('VIEW COMPILED CONTRACT JSON'),'Product Contract UI missing');
console.log('10.48.0 Product Contract + Journey Test Lab gate: PASS');
