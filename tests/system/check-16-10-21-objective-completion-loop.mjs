assert.match(routes,/OBJECTIVE_REASSESSMENT_REQUIRED/,'execution must be blocked until reassessment');
assert.match(routes,/getPlatformCommandCenter\(env,plan\.scope\|\|\{\}\)/,'reassessment must use canonical context service');
assert.match(ui,/objectiveInputForm/,'Command Center must expose user input for the next objective step');
assert.match(ui,/SUBMIT DATA &amp; REASSESS/,'input submission must communicate reassessment');
assert.match(ui,/\/reassess/,'UI must request canonical reassessment after input');
assert.match(release,/# Mission Execution 16\.10\.21/);
console.log('16.10.21 Objective Completion Loop contract: PASS');
