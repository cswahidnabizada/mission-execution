import fs from 'node:fs';
import path from 'node:path';
const read=f=>fs.readFileSync(path.join(process.cwd(),f),'utf8');
const assert=(ok,msg)=>{if(!ok)throw new Error(msg)};
const version=read('VERSION').trim();
const pkg=JSON.parse(read('package.json'));
const registry=read('public/assets/js/frontend/admin/workspace-registry.js');
const service=read('src/worker/modules/admin-control/command-center.service.js');
const center=read('public/assets/js/frontend/admin/command-center.js');
const shell=read('public/assets/js/frontend/admin/shell.js');
const drawer=read('public/assets/js/frontend/admin/detail-drawer.js');
const context=read('public/assets/js/frontend/core/experience-context.js');
assert(/^\d+\.\d+\.\d+$/.test(version),'current release must preserve 10.55/10.56 governance contract');
assert(pkg.version===version,'package version mismatch');
assert(registry.includes("authority:")&&registry.includes("access:")&&registry.includes("journey:"),'workspace governance metadata is not exposed');
const keys=[...registry.matchAll(/\['[^']+','([^']+)'/g)].map(m=>m[1]);
assert(keys.length>=30,`expected at least 30 canonical workspaces, got ${keys.length}`);
assert(new Set(keys).size===keys.length,'duplicate canonical workspace keys');
for(const key of keys) assert(registry.includes(`'${key}'`),`workspace ${key} missing from registry`);
assert(service.includes('workspaceStates'),'Control Plane must return canonical dynamic workspace state');
assert(!service.includes('const categories=['),'backend must not duplicate frontend workspace categories');
assert(!service.includes("{key:'operations',label:'Operations'"),'Operations must not be a duplicate workspace');
assert(center.includes('ADMIN_WORKSPACE_GROUPS')&&center.includes('workspaceStates'),'Command Center must compose registry + dynamic state');
assert(center.includes('data-attention-detail')&&center.includes('openAdminDrawer'),'Command Center must expose governed detail drawers');
assert(shell.includes('readExperienceContext')&&shell.includes('writeExperienceContext'),'admin shell must use persistent experience context');
assert(drawer.includes('admin-detail-drawer'),'detail drawer implementation missing');
assert(context.includes('sessionStorage')&&context.includes('surface'),'experience context must be UI-only and surface-scoped');
console.log('10.55.x Control Plane Governance compatibility gate: PASS');
