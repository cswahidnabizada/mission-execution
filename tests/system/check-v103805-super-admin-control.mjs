import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const assert=(ok,msg)=>{if(!ok)throw new Error(msg)};
const pkg=JSON.parse(read('package.json'));
assert(read('VERSION').trim()==='10.38.12','VERSION must be 10.38.12');
assert(pkg.version==='10.38.12','package.json must be 10.38.12');
const admin=read('public/assets/js/frontend/admin/admin.js');
assert(admin.includes('e.status=r.status'),'frontend API errors must preserve HTTP status');
assert(admin.includes('/api/platform/access/admin/login'),'dedicated platform login endpoint missing');
assert(admin.includes('/api/platform/access/admin/logout'),'canonical platform logout endpoint missing');
assert(admin.includes('id="logoutPlatform"'),'platform error state must provide sign out');
assert(admin.includes('data-error-signout'),'platform section errors must provide sign out');
assert(admin.includes('SIGN IN AS SUPER ADMIN'),'Super Admin reauthentication path missing');
assert(admin.includes('state.superAdmin&&allCore'),'country launch must require Super Admin and core readiness');
assert(admin.includes('id="launchCountryCode"'),'country launch selector missing');
assert(admin.includes('d.countries||[]'),'country launch selector must use configured country catalog');
const routes=read('src/worker/modules/admin-control/admin-control.routes.js');
assert(routes.includes("/api/platform/access/admin/login"),'platform login route missing');
assert(routes.includes("/api/platform/access/admin/logout"),'platform logout route missing');
assert(routes.includes('destroyPlatformSuperAdministrator'),'platform logout must destroy Super Admin authority');
assert(routes.includes('PLATFORM_SUPER_ADMIN_SECRET'),'platform login must use infrastructure secret');
const session=read('src/worker/security/platform-super-administrator.js');
assert(session.includes('crypto.subtle.sign'),'Super Admin session must be cryptographically signed');
assert(session.includes('HMAC'),'Super Admin session must use HMAC');
assert(!session.includes('env.KV_BINDING.get(`platform_super_admin:'),'Super Admin primary session validation must not depend on eventually-consistent KV');
assert(session.includes('PLATFORM_SUPER_ADMIN_SECRET'),'Super Admin elevation must remain secret-backed');
const launch=read('src/worker/security/country-product-launch.service.js');
assert(launch.includes("row.status!=='validated'"),'country activation must require validation');
assert(launch.includes('readiness.valid!==true'),'country activation must require valid readiness');
assert(launch.includes("status='active',active=1"),'country launch must create canonical active state');
assert(!routes.includes('onmission_platform_reviewer'),'platform logout must not reference reviewer cookie');
console.log('10.38.12 Super Admin access, recovery and country launch control: PASS');
