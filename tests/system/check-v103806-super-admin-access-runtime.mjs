import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const assert=(ok,msg)=>{if(!ok)throw new Error(msg)};
const pkg=JSON.parse(read('package.json'));
assert(read('VERSION').trim()==='10.38.12','VERSION must be 10.38.12');
assert(pkg.version==='10.38.12','package.json must be 10.38.12');
const admin=read('public/assets/js/frontend/admin/admin.js');
const loadBlock=admin.slice(admin.indexOf('async function load(){'));
assert(loadBlock.includes("await api('/api/platform/admin/super-admin/session')"),'Platform access must verify Super Admin session before opening the Studio');
assert(!loadBlock.includes("await api('/api/platform/admin/session')"),'Platform access must not use reviewer session as the primary entry check');
assert(loadBlock.includes("if(Number(error?.status)===401||Number(error?.status)===403)"),'authorization failures must open the platform sign-in surface');
assert(admin.includes('/api/platform/access/admin/login'),'dedicated secret login route missing');
assert(admin.includes('/api/platform/access/admin/logout'),'canonical platform logout missing');
assert(admin.includes('id="logoutPlatform"'),'platform error recovery must include sign out');
const pa=read('src/worker/security/platform-administrator.js');
assert(pa.includes('readPlatformSuperAdministrator'),'platform administrator authority must recognize Super Admin sessions');
assert(pa.includes('superAdmin:true'),'Super Admin authority must be explicit');
const routes=read('src/worker/modules/admin-control/admin-control.routes.js');
assert(routes.includes("/api/platform/access/admin/login"),'platform secret login endpoint missing');
assert(routes.includes('PLATFORM_SUPER_ADMIN_SECRET'),'platform login must use infrastructure secret');
assert(routes.includes("/api/platform/admin/super-admin/session"),'Super Admin session endpoint missing');
const html=read('public/platform/access/admin/index.html');
assert(html.includes('10.38.12'),'platform access assets must use current release identity');
console.log('10.38.12 Super Admin access runtime convergence: PASS');
