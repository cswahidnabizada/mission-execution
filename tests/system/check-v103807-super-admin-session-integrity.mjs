import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const assert=(ok,msg)=>{if(!ok)throw new Error(msg)};
const pkg=JSON.parse(read('package.json'));
assert(read('VERSION').trim()==='10.38.12','VERSION must be 10.38.12');
assert(pkg.version==='10.38.12','package.json must be 10.38.12');
const superAdmin=read('src/worker/security/platform-super-administrator.js');
assert(superAdmin.includes('crypto.subtle.sign'),'Super Admin sessions must be cryptographically signed');
assert(superAdmin.includes('HMAC'),'Super Admin session signing must use HMAC');
assert(superAdmin.includes('PLATFORM_SUPER_ADMIN_SECRET'),'Super Admin session verification must use the Worker secret');
assert(superAdmin.includes('SESSION_TTL_SECONDS=30*60'),'Super Admin session TTL must remain bounded');
assert(superAdmin.includes("parts[0]!=='v1'"),'Super Admin session format must be versioned');
assert(!superAdmin.includes('env.KV_BINDING.get(`platform_super_admin:'),'Super Admin primary authentication must not depend on eventually-consistent KV reads');
const security=read('src/worker/security/request-security.js');
assert(security.includes('getSetCookie')||security.includes('getAll'), 'security response wrapping must preserve multiple Set-Cookie headers');
assert(security.includes('Set-Cookie'), 'security response wrapper must explicitly handle Set-Cookie');
const routes=read('src/worker/modules/admin-control/admin-control.routes.js');
assert(routes.includes('createPlatformSuperAdminSession'),'dedicated login must create the canonical Super Admin session');
assert(routes.includes('PLATFORM_SUPER_ADMIN_TTL'),'dedicated login must use the canonical Super Admin TTL');
const admin=read('public/assets/js/frontend/admin/admin.js');
assert(admin.includes("/api/platform/access/admin/login"),'dedicated platform login route missing');
assert(admin.includes("/api/platform/admin/super-admin/session"),'dedicated Super Admin session check missing');
assert(admin.includes('id="logoutPlatform"'),'platform recovery surface must retain Sign Out');
console.log('10.38.12 Super Admin session integrity: PASS');
