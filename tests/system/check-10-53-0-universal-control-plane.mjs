import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const assert=(ok,msg)=>{if(!ok)throw new Error(msg)};
const version=read('VERSION').trim();
const pkg=JSON.parse(read('package.json'));
const service=read('src/worker/modules/admin-control/command-center.service.js');
const runtime=read('public/assets/js/frontend/admin/admin-runtime.js');
const shell=read('public/assets/js/frontend/admin/shell.js');
const registry=read('public/assets/js/frontend/admin/workspace-registry.js');
const ui=read('public/assets/js/frontend/admin/command-center.js');
const css=read('public/assets/css/admin-control.css');
const release=read('RELEASE.md');
assert(/^\d+\.\d+\.\d+$/.test(version),`current release must be 10.53.x: ${version}`);
assert(pkg.version===version,'package version mismatch');
for(const x of ['getControlPlane','getProductBuildControl','getProductMonitor','evaluateProductLaunchReadiness'])assert(service.includes(x),`Command Center missing canonical projection ${x}`);
for(const x of ['surface','workspaceStates','queue','lifecycle','unavailableAuthorities','preview'])assert(service.includes(x),`Command Center surface projection missing ${x}`);
assert(service.includes('parseJson(activeLaunch.manifest_json)'),'country/sector lens must parse the canonical launch manifest');
assert(service.includes('evaluateProductLaunchReadiness(env,{countryCode:country'),'country/sector lens must use canonical readiness authority');
assert(!service.includes('parseJson(activeLaunch.manifest_json):{};\n    const manifestSectors')||service.includes('const parseJson='),'manifest parser must be locally defined');
assert(runtime.includes('commandScope'),'Admin runtime must persist the selected command-center lens');
for(const x of ['MARKET STUDIO','OPERATE','GOVERN','RESOURCES','COMMAND'])assert(registry.includes(`label:'${x}'`),`workspace category missing ${x}`);
for(const x of ['PLATFORM CONTROL','CURRENT SITUATION','CURRENT ACTION','RELEASE JOURNEY','RECENT ACTIVITY','AUTHORITY AVAILABILITY'])assert(ui.includes(x),`Command Center surface missing ${x}`);
for(const x of ['control-center','control-metrics','workspace-index-grid','journey-track','platform-context'])assert(css.includes(x),`Command Center UI styling missing ${x}`);
assert(release.includes('Unified Operational Experience')&&release.includes('Admin orchestrates'),'release documentation must describe the new Control Plane boundary');
console.log('10.53.0 Universal Control Plane Command Center gate: PASS');
