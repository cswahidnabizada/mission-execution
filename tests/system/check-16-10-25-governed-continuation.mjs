import fs from 'node:fs';
import assert from 'node:assert/strict';
const version=fs.readFileSync('VERSION','utf8').trim();
const pkg=JSON.parse(fs.readFileSync('package.json','utf8'));
const routes=fs.readFileSync('src/worker/modules/admin-control/objective-orchestrator.routes.js','utf8');
const ui=fs.readFileSync('public/assets/js/frontend/admin/command-center.js','utf8');
const release=fs.readFileSync('RELEASE.md','utf8');
const [major,minor,patch]=version.split('.').map(Number);
assert.ok(major>16||(major===16&&(minor>10||(minor===10&&patch>=25))),'candidate must preserve governed continuation');
assert.ok(pkg.version.localeCompare('16.10.25', undefined, {numeric:true})>=0, 'package must preserve 25 objective capability');
assert.match(routes,/objective-runs\/:runId\/continuation/,'continuation must be tied to an objective run');
assert.match(routes,/READY_TO_EXECUTE_ONE_STEP/,'continuation must select at most one valid next step');
assert.match(routes,/BLOCKED_NO_REGISTERED_EXECUTOR/,'unknown executors must be blocked');
assert.match(routes,/OBJECTIVE_GAP_ASSESSMENT_REQUIRED/,'execution must require fresh gap assessment');
assert.match(routes,/requires_approval=0 OR status='APPROVED'/,'approval-required steps cannot execute before approval');
assert.match(routes,/requirePlatformSuperAdminStepUp/,'execution must retain step-up authorization');
assert.match(routes,/OBJECTIVE_CONTINUATION_SELECTED/,'continuation decisions must be evented');
assert.match(ui,/\/continuation/,'UI must ask the governed continuation engine for next step');
assert.match(ui,/selected\.continuation\.status!=='READY_TO_EXECUTE_ONE_STEP'/,'UI must stop if no step is authorized');
assert.match(release,/# Mission Execution 16\.10\.25/);
console.log('16.10.25 Governed Continuation: PASS');
