import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const must=(s,needle,msg)=>{if(!s.includes(needle))throw new Error(msg)};
const audit=read('src/worker/security/audit.js');
const privacy=read('src/worker/modules/privacy/privacy.service.js');
const routes=read('src/worker/modules/privacy/privacy.routes.js');
const worker=read('_worker.js');
const app=read('src/worker/app.js');
const wrangler=read('wrangler.jsonc');
const pkg=JSON.parse(read('package.json'));
must(audit,'SENSITIVE_KEY','Audit redaction missing');
must(audit,'MAX_METADATA_BYTES','Audit metadata bound missing');
must(privacy,'exportPersonalData','Personal data export missing');
must(privacy,'purgeExpiredOperationalData','Retention cleanup missing');
must(routes,'/api/account/privacy/export','Privacy export route missing');
must(routes,'requireSession','Privacy route authentication missing');
must(app,'registerPrivacyRoutes','Privacy routes not registered');
must(worker,'scheduled','Scheduled retention handler missing');
must(wrangler,'AUDIT_RETENTION_DAYS','Audit retention configuration missing');
if(pkg.version!==read('VERSION').trim())throw new Error('Package/VERSION mismatch');
if(!/^10\.3\d\.\d+$/.test(pkg.version))throw new Error('Unexpected release version');
console.log(`${pkg.version} inherited privacy governance: PASS`);
